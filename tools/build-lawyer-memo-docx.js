// «**жирный** обычный» → куски текста.
const rich = (text, base = {}) =>
  text
    .split(/(\*\*[^*]+\*\*)/)
    .filter(Boolean)
    .map((part) => (part.startsWith("**") ? new TextRun({ text: part.slice(2, -2), bold: true, ...base }) : new TextRun({ text: part, ...base })));

const para = (children, options = {}) => new Paragraph({ spacing: { after: 100 }, ...options, children });
const body = (text, base = {}) => para(rich(text, base));
const bullet = (text) => new Paragraph({ numbering: { reference: "bullets", level: 0 }, spacing: { after: 80 }, children: rich(text) });
const heading = (text, level = 1) => new Paragraph({ heading: level === 1 ? "Heading1" : "Heading2", children: [new TextRun(text)] });

const cell = (children, width, { fill, bold, size = 19, color } = {}) =>
  new TableCell({
    width: { size: width, type: WidthType.DXA },
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    verticalAlign: VerticalAlign.TOP,
    ...(fill && { shading: { type: ShadingType.CLEAR, fill, color: "auto" } }),
    children: [new Paragraph({ spacing: { after: 0 }, children: rich(children, { size, bold, color }) })],
  });

const table = (widths, head, rows) =>
  new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: widths,
    borders: { top: hair, bottom: hair, left: hair, right: hair, insideHorizontal: hair, insideVertical: hair },
    rows: [
      new TableRow({ tableHeader: true, children: head.map((t, i) => cell(t, widths[i], { fill: BRAND_TINT, bold: true, color: BRAND_DK })) }),
      ...rows.map((row) => new TableRow({ cantSplit: true, children: row.map((t, i) => cell(t, widths[i], i === 0 ? { fill: PAPER_2, bold: true } : {})) })),
    ],
  });

const box = (lines, fill = PAPER_2) =>
  new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: [W],
    borders: { top: NONE, bottom: NONE, left: NONE, right: NONE, insideHorizontal: NONE, insideVertical: NONE },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: W, type: WidthType.DXA },
            margins: { top: 140, bottom: 100, left: 200, right: 200 },
            shading: { type: ShadingType.CLEAR, fill, color: "auto" },
            children: lines.map((text) => new Paragraph({ spacing: { after: 90 }, children: rich(text) })),
          }),
        ],
      }),
    ],
  });

