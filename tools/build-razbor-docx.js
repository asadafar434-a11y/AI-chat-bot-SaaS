/* Маркетинговый бюджет — единственная статья, растущая с этапом.
   Личные расходы основателя в модели НЕ учитываются: это не расход проекта. */
const MKT = (m) => (m <= 6 ? 5000 : m <= 12 ? 10000 : m <= 18 ? 20000 : 50000);

const PLAN = [0, 0, 1, 2, 4, 5, 5, 6, 6, 7, 7, 8, 8, 9, 9, 10, 10, 11, 11, 12, 12, 13, 13, 14];

function model(plan) {
  let clients = 0;
  let cash = BUDGET;
  const out = [];
  for (let m = 1; m <= 24; m++) {
    const churn = Math.round(clients * CHURN);
    const nw = plan[m - 1];
    clients = clients - churn + nw;
    const mrr = clients * ARPA;
    const gp = Math.round(mrr * GM);
    const mkt = MKT(m);
    const cost = FIXED + mkt;
    cash += gp - cost;
    out.push({ m, nw, churn, clients, mrr, gp, mkt, cost, cash });
  }
  return out;
}

