/* ---------- разбор **жирного** ---------- */
function runs(text, o = {}) {
  return String(text)
    .split(/(\*\*[^*]+\*\*)/g)
    .filter(Boolean)
    .map((p) =>
      p.startsWith("**") && p.endsWith("**")
        ? new TextRun({ text: p.slice(2, -2), bold: true, font: FONT, ...o })
        : new TextRun({ text: p, font: FONT, ...o })
    );
}

