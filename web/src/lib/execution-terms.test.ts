// Что договор требует от поставщика сверх товара: место, срок, обязанности, пункт «Цена договора включает» — npm test.
import assert from "node:assert/strict";
import { test } from "node:test";
import { executionTerms, termsLine } from "./execution-terms.ts";

const BRATSK = [
  "Место поставки товара: 665717, Иркутская область, г. Братск, ж.р. Центральный, ул. Курчатова, д. 6. Условия и сроки поставки товара: Товар поставляется в течение 15 календарных дней с момента заключения договора",
  "1 | Офисное кресло Chairman 696 LT | Офисное кресло на колесах с подъемным механизмом. Максимальная нагрузка – 150 кг.",
  "1.6.1. Выполняет все виды погрузо-разгрузочных мероприятий, осуществляет подъем Товара на этаж здания, в котором расположен Заказчик.",
  "1.6.2. Поставщик самостоятельно собирает и устанавливает мебель, входящую в поставку.",
  "2.5. Цена Договора включает в себя: стоимость Товара в полной комплектации, расходы, связанные с погрузо-разгрузочными работами, транспортировкой, доставкой Товара до места передачи Заказчику.",
].join("\n");

test("Братский дом-интернат: место — г. Братск, 15 календарных дней, разгрузка, подъём на этаж, сборка и установка, п. 2.5", () => {
  const t = executionTerms([{ name: "Извещение .docx", text: BRATSK }]);
  assert.deepEqual(t, { place: "г. Братск", term: "15 календарных дней", duties: ["разгрузка", "подъём на этаж", "сборка", "установка"], priceClause: "2.5" });
  assert.equal(
    termsLine(t),
    "Договор: поставка в течение 15 календарных дней, место — г. Братск; поставщик сам делает разгрузку, подъём на этаж, сборку и установку — это входит в цену договора (п. 2.5).",
  );
});

test("«подъёмный механизм» кресла в таблице описания — не подъём на этаж; без города — регион; ничего нет — null", () => {
  const t = executionTerms([{ name: "ТЗ", text: "1 | Кресло | с подъемным механизмом, сборка не требуется |\nМесто поставки: Иркутская область, Братский район" }]);
  assert.deepEqual(t.duties, []);
  assert.equal(t.place, "Иркутская область");
  assert.equal(termsLine({ place: null, term: null, duties: [], priceClause: null }), null);
  assert.equal(termsLine({ place: null, term: null, duties: ["сборка"], priceClause: null }), "Поставщик сам делает сборку — это входит в цену договора.");
  assert.equal(executionTerms([{ name: "x", text: "Поставка товара в течение 21 рабочего дня" }]).term, "21 рабочего дня");
});
