// Тип документа закупки: определяется по имени файла и началу текста, без AI.
// Используется для подсказки пользователю («что это за файл?»), и в AI-запросе —
// чтобы модель сначала искала формы именно в customer_form документах.

export type DocKind =
  | "notice"         // Извещение о проведении закупки
  | "documentation"  // Документация о закупке
  | "technical_spec" // Техническое задание
  | "info_card"      // Информационная карта
  | "contract"       // Проект контракта / договора
  | "customer_form"  // Форма/бланк/шаблон заказчика (приложение с полями для заполнения)
  | "price_form"     // Форма ценового предложения
  | "declaration"    // Декларация
  | "regulation"     // Порядок оценки, регламент, критерии
  | "other";

export const DOC_KIND_LABELS: Record<DocKind, string> = {
  notice:         "Извещение",
  documentation:  "Документация",
  technical_spec: "Техническое задание",
  info_card:      "Информационная карта",
  contract:       "Проект контракта",
  customer_form:  "Форма заказчика",
  price_form:     "Форма цены",
  declaration:    "Декларация",
  regulation:     "Порядок оценки",
  other:          "Документ",
};

type Rule = [RegExp, DocKind];

// Правила по имени файла — проверяются первыми, чаще всего достаточно.
const NAME_RULES: Rule[] = [
  [/извещени/i, "notice"],
  [/информационн.*карт|карт.*информ/i, "info_card"],
  [/документаци/i, "documentation"],
  [/техническ.*задани|тех.*задани|(?:^|[^а-яёА-ЯЁa-zA-Z0-9])ТЗ(?:[^а-яёА-ЯЁa-zA-Z0-9]|$)/i, "technical_spec"],
  [/проект.*контракт|проект.*договор|контракт|договор.*поставк/i, "contract"],
  [/декларац/i, "declaration"],
  [/ценов.*предложени|коммерческ.*предложени|прайс/i, "price_form"],
  [/порядок.*оценк|критери.*оценк|регламент/i, "regulation"],
  // Формы: бланки, анкеты, приложения с шаблонами
  [/форм[аы]|бланк|анкет[аы]|приложени|шаблон|заявк[аа].*участи/i, "customer_form"],
];

// Правила по первым ~1000 символам текста — когда имя неинформативно.
const TEXT_RULES: Rule[] = [
  [/извещение о проведении|сведения о закупке|единая информационная система|ЕИС/i, "notice"],
  [/информационная карта/i, "info_card"],
  [/техническое задание|технические требования|требования к товарам?|требования к услугам?/i, "technical_spec"],
  [/документация о закупке|конкурсная документация|аукционная документация/i, "documentation"],
  [/проект контракта|проект договора|государственный контракт|муниципальный контракт/i, "contract"],
  [/декларация о принадлежности|декларация о соответствии/i, "declaration"],
  [/ценовое предложение|коммерческое предложение|предложение о цене/i, "price_form"],
  [/порядок оценки|критерии оценки|методика оценки/i, "regulation"],
  // Форма: признаки шаблона для заполнения
  [
    /заявка на участие|форма заявки|бланк заявки|заполняется участником|наименование участника|место нахождения.*участника|сведения об участнике|анкета участника/i,
    "customer_form",
  ],
];

/**
 * Классифицирует документ по имени файла и началу текста.
 * Чисто детерминированная функция — без AI, без сети.
 */
export function classifyDoc(name: string, text: string): DocKind {
  const baseName = name.replace(/\.[^.]+$/, ""); // без расширения
  for (const [re, kind] of NAME_RULES) {
    if (re.test(baseName)) return kind;
  }
  const head = text.slice(0, 1000);
  for (const [re, kind] of TEXT_RULES) {
    if (re.test(head)) return kind;
  }
  return "other";
}

/** True если документ является формой/бланком заказчика (нужно искать шаблоны). */
export const isCustomerForm = (kind: DocKind): boolean =>
  kind === "customer_form" || kind === "price_form" || kind === "declaration";
