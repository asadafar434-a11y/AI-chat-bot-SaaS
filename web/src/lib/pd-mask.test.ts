// Проверка маскировки персональных данных: npm test.
import assert from "node:assert/strict";
import { test } from "node:test";
import { PdMasker } from "./pd-mask.ts";

const mask = (text: string) => new PdMasker(true).mask(text);
const hidden = (text: string, value: string) => !mask(text).includes(value);

test("телефоны", () => {
  for (const phone of ["+7 (495) 123-45-67", "8 (800) 555-35-35", "8-916-123-45-67", "+79161234567", "(4012) 12-34-56", "+375 29 123-45-67"]) {
    assert.ok(hidden(`Контактный телефон: ${phone}.`, phone), phone);
  }
  assert.ok(hidden("тел. 12-34-56, доб. 5", "12-34-56"));
  assert.ok(hidden("Тел.: 89161234567", "89161234567"));
});

test("не телефоны: коды, суммы, номера извещений", () => {
  const text =
    "ОКТМО 80701000001. Извещение № 0373200000123000001. НМЦК 80 000 000 000 руб. Цена 3 000 000,00 руб. ОКПД2 84.11.11.000. Реестровый номер 32312345678.";
  assert.equal(mask(text), text);
});

test("почта, паспорт, СНИЛС, ИНН и ОГРНИП физлица, счёт ИП, дата рождения", () => {
  const cases: [string, string][] = [
    ["E-mail: ivanov.ii@mail.ru", "ivanov.ii@mail.ru"],
    ["почта@сайт.рф", "почта@сайт.рф"],
    ["паспорт серии 45 06 № 123456, выдан ОВД", "45 06 № 123456"],
    ["Паспорт: 4506 123456", "4506 123456"],
    ["код подразделения 770-001", "770-001"],
    ["СНИЛС 112-233-445 95", "112-233-445 95"],
    ["СНИЛС: 12345678964", "12345678964"],
    ["ИНН 500100732259", "500100732259"],
    ["реквизиты: 771234567859", "771234567859"],
    ["ОГРНИП 304500116000157", "304500116000157"],
    ["р/с 40802810400000123456", "40802810400000123456"],
    ["дата рождения: 01.02.1970", "01.02.1970"],
    ["1970 г.р.", "1970"],
  ];
  for (const [text, value] of cases) assert.ok(hidden(text, value), text);
});

test("реквизиты организации остаются", () => {
  const text = "ИНН 7707083893, КПП 773601001, ОГРН 1027700132195, р/с 40702810400000123456, БИК 044525225, СНИЛС сотрудника не требуется.";
  assert.equal(mask(text), text);
});

test("адрес регистрации — только когда похож на адрес", () => {
  const masked = mask("Адрес регистрации: 123456, г. Москва, ул. Ленина, д. 1, кв. 2");
  assert.equal(masked, "Адрес регистрации: ⟦АДРЕС-1⟧");
  const requirement = "Анкета должна содержать ФИО, адрес регистрации, паспортные данные.";
  assert.equal(mask(requirement), requirement);
});

test("ФИО полностью, с инициалами и в разных падежах — один человек", () => {
  const masker = new PdMasker(true);
  const text = masker.mask(
    "Генеральный директор Иванов Иван Иванович. В лице генерального директора Иванова Ивана Ивановича. Подпись: /И.И. Иванов/. Исполнитель: Иванов И.И."
  );
  assert.equal(
    text,
    // Точка в конце — точка инициала: она уходит в метку и возвращается с ФИО.
    "Генеральный директор ⟦ФИО-1⟧. В лице генерального директора ⟦ФИО-1/р⟧. Подпись: /⟦ФИО-1/ИФ⟧/. Исполнитель: ⟦ФИО-1/ФИ⟧"
  );
});

test("женские отчества, порядок «Имя Отчество Фамилия», заглавные буквы", () => {
  assert.equal(mask("Контактное лицо: Петрова Анна Сергеевна"), "Контактное лицо: ⟦ФИО-1⟧");
  assert.equal(mask("с Петровой Анной Сергеевной"), "с ⟦ФИО-1/т⟧");
  assert.equal(mask("Анна Сергеевна Петрова, специалист"), "⟦ФИО-1⟧, специалист");
  assert.equal(mask("ИВАНОВ ИВАН ИВАНОВИЧ"), "⟦ФИО-1⟧");
  assert.equal(mask("Уважаемый Иван Иванович!"), "Уважаемый ⟦ФИО-1/ИО⟧!");
});

test("мужчина и женщина с той же фамилией и инициалами — разные люди", () => {
  assert.equal(mask("Иванов Алексей Сергеевич и Ивановой Анны Сергеевны"), "⟦ФИО-1⟧ и ⟦ФИО-2/р⟧");
});

test("не ФИО: «Ф.И.О.», «М.П.», «И.О. Директора», должности", () => {
  const text = "Ф.И.О. участника. М.П. Генеральный директор. И.О. Директора. Российской Федерации. Приложение А.Б.";
  assert.equal(mask(text), text);
});

test("одно значение — одна метка во всех текстах, и то же при повторе", () => {
  const first = new PdMasker(true);
  const second = new PdMasker(true);
  const docs = ["Тел. +7 (495) 123-45-67, Петрова Анна Сергеевна", "Контакты: +7 (495) 123-45-67"];
  const a = docs.map((d) => first.mask(d));
  const b = docs.map((d) => second.mask(d));
  assert.deepEqual(a, b);
  assert.equal(a[1], "Контакты: ⟦ТЕЛЕФОН-1⟧");
});

test("уже скрытое значение находится и без пометки", () => {
  const masker = new PdMasker(true);
  masker.mask("Адрес регистрации: 123456, г. Москва, ул. Ленина, д. 1");
  assert.equal(masker.mask("Почтовый адрес: 123456, г. Москва, ул. Ленина, д. 1"), "Почтовый адрес: ⟦АДРЕС-1⟧");
  assert.equal(
    mask("Адрес регистрации: 410012, г. Саратов, ул. Чернышевского, д. 10\nПочтовый адрес: 410012, г. Саратов, ул. Чернышевского, д. 10"),
    "Адрес регистрации: ⟦АДРЕС-1⟧\nПочтовый адрес: ⟦АДРЕС-1⟧"
  );
});

test("обратная замена: текст, JSON, поток по кусочкам", () => {
  const masker = new PdMasker(true);
  const source = "Руководитель Иванов Иван Иванович, тел. +7 (495) 123-45-67";
  const masked = masker.mask(source);
  assert.equal(masker.unmask(masked), source);
  assert.deepEqual(masker.unmaskDeep({ items: [{ quote: masked }], n: 1 }), { items: [{ quote: source }], n: 1 });

  const stream = masker.stream();
  const pieces = ["Подписывает ⟦Ф", "ИО-1⟧", ", звонить ⟦ТЕЛЕФОН", "-1⟧."];
  const out = pieces.map((p) => stream.push(p)).join("") + stream.flush();
  assert.equal(out, "Подписывает Иванов Иван Иванович, звонить +7 (495) 123-45-67.");
});

test("форма ФИО, которой нет в тексте, — основная форма человека; чужая метка — не показывается", () => {
  const masker = new PdMasker(true);
  masker.mask("Иванов Иван Иванович");
  assert.equal(masker.unmask("в лице ⟦ФИО-1/р⟧"), "в лице Иванов Иван Иванович");
  assert.equal(masker.unmask("⟦ФИО-7⟧"), "[данные скрыты]");
  assert.equal(masker.unmask("⟦ СЧЁТ-1 ⟧"), "[данные скрыты]");
});

test("выключено — текст не меняется", () => {
  const masker = new PdMasker(false);
  const text = "Иванов Иван Иванович, +7 (495) 123-45-67";
  assert.equal(masker.mask(text), text);
});
