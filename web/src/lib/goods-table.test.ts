import assert from "node:assert/strict";
import { test } from "node:test";
import { findGoodsTable } from "./goods-table.ts";
import { positionsFromDocuments } from "./indicative-price.ts";

const TZ = [
  "Приложение № 1 — Технические требования",
  "",
  "№ п/п | Наименование товара | Ед. изм. | Количество | Требования к товару",
  "1 | Агрегат сварочный дизельный АДД-4004, 400 А | шт | 3 | Двигатель дизельный, ресурс не менее 5000 ч",
  "2 | Агрегат сварочный бензиновый, 200 А | шт | 2,5 | Масса не более 90 кг",
  "Итого | | | 5,5 |",
  "",
  "Поставка осуществляется до склада заказчика.",
].join("\n");

test("таблица товаров из технических требований: название, единица, количество; итоговая строка и пояснения под таблицей не берутся", () => {
  const t = findGoodsTable([{ name: "Приложение №1 к ДоЗ - Технические требования.docx", text: TZ }]);
  assert.ok(t);
  assert.equal(t.doc, "Приложение №1 к ДоЗ - Технические требования.docx");
  assert.deepEqual(t.rows, [
    { name: "Агрегат сварочный дизельный АДД-4004, 400 А", unit: "шт", qty: 3 },
    { name: "Агрегат сварочный бензиновый, 200 А", unit: "шт", qty: 2.5 },
  ]);
});

test("позиции для расчёта: бланка «Спецификация» нет — берётся таблица товаров, цен заказчика у позиций нет", () => {
  const found = positionsFromDocuments([{ name: "ТЗ.docx", text: TZ }]);
  assert.ok(found);
  assert.equal(found.positions.length, 2);
  assert.deepEqual(found.positions[1], { id: "doc-2", name: "Агрегат сварочный бензиновый, 200 А", unit: "шт", qty: "2,5", analogs: [] });
  assert.equal(found.positions[0].customerUnit, undefined);
});

test("не товары: перечень документов и пункты документации не принимаются за позиции; таблица без количества тоже", () => {
  const docs = [
    "№ п/п | Наименование документа | Количество экземпляров\n1 | Заявка на участие | 1\n2 | Анкета участника | 2",
    "№ п/п | Наименование пункта | Содержание пункта\n1.2.1 | Способ закупки | Аукцион",
    "№ п/п | Наименование | Цена\n1 | Агрегат сварочный | 5000",
  ];
  for (const text of docs) assert.equal(findGoodsTable([{ name: "ДоЗ.docx", text }]), null, text.slice(0, 40));
});

test("расчёт НМЦК заказчика с количествами и ценами поставщиков в позиции не берётся (это не бланк участника)", () => {
  const text = "Обоснование начальной (максимальной) цены\n№ п/п | Наименование товара | Ед. изм. | Количество | Цена\n1 | Агрегат сварочный | шт | 3 | 5000";
  assert.equal(findGoodsTable([{ name: "Обоснование НМЦ.docx", text }]), null);
});

test("строка с другим числом ячеек (объединённые ячейки) и количество «3 шт.» в одной ячейке читаются без выдумок", () => {
  const text = ["№ | Наименование продукции | Количество", "1 | Электроды УОНИ-13/55, 4 мм | 120 кг", "2 | Маска сварщика | | лишняя ячейка", "3 | Перчатки сварочные | 40 пар."].join("\n");
  const t = findGoodsTable([{ name: "ТЗ.docx", text }]);
  assert.ok(t);
  assert.deepEqual(t.rows, [
    { name: "Электроды УОНИ-13/55, 4 мм", unit: "кг", qty: 120 },
    { name: "Перчатки сварочные", unit: "пар.", qty: 40 },
  ]);
});
