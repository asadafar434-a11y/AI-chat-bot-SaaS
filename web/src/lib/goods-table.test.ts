import assert from "node:assert/strict";
import { test } from "node:test";
import { findGoodsTable } from "./goods-table.ts";
import { positionsFromDocuments } from "./indicative-price.ts";

const TZ = [
  "Приложение № 1 — Технические требования",
  "",
  "№ п/п | Наименование товара | Ед. изм. | Количество | Требования к товару",
  "1 | Агрегат сварочный дизельный АДД-4004, 400 А | шт | 3 | Двигатель дизельный, ресурс не менее 5000 ч",
  "2 | Агрегат сварочный бензиновый, 200 А | шт | 2,5 | Масса не более 90 кг",
  "Итого | | | 5,5 |",
  "",
  "Поставка осуществляется до склада заказчика.",
].join("\n");

test("таблица товаров из технических требований: название, единица, количество; итоговая строка и пояснения под таблицей не берутся", () => {
  const t = findGoodsTable([{ name: "Приложение №1 к ДоЗ - Технические требования.docx", text: TZ }]);
  assert.ok(t);
  assert.equal(t.doc, "Приложение №1 к ДоЗ - Технические требования.docx");
  assert.deepEqual(t.rows, [
    { name: "Агрегат сварочный дизельный АДД-4004, 400 А", unit: "шт", qty: 3 },
    { name: "Агрегат сварочный бензиновый, 200 А", unit: "шт", qty: 2.5 },
  ]);
});

test("позиции для расчёта: бланка «Спецификация» нет — берётся таблица товаров, цен заказчика у позиций нет", () => {
  const found = positionsFromDocuments([{ name: "ТЗ.docx", text: TZ }]);
  assert.ok(found);
  assert.equal(found.positions.length, 2);
  assert.deepEqual(found.positions[1], { id: "doc-2", name: "Агрегат сварочный бензиновый, 200 А", unit: "шт", qty: "2,5", analogs: [] });
  assert.equal(found.positions[0].customerUnit, undefined);
});

test("не товары: перечень документов и пункты документации не принимаются за позиции; таблица без количества тоже", () => {
  const docs = [
    "№ п/п | Наименование документа | Количество экземпляров\n1 | Заявка на участие | 1\n2 | Анкета участника | 2",
    "№ п/п | Наименование пункта | Содержание пункта\n1.2.1 | Способ закупки | Аукцион",
    "№ п/п | Наименование | Цена\n1 | Агрегат сварочный | 5000",
  ];
  for (const text of docs) assert.equal(findGoodsTable([{ name: "ДоЗ.docx", text }]), null, text.slice(0, 40));
});

test("расчёт НМЦК заказчика с количествами и ценами поставщиков в позиции не берётся (это не бланк участника)", () => {
  const text = "Обоснование начальной (максимальной) цены\n№ п/п | Наименование товара | Ед. изм. | Количество | Цена\n1 | Агрегат сварочный | шт | 3 | 5000";
  assert.equal(findGoodsTable([{ name: "Обоснование НМЦ.docx", text }]), null);
});

test("строка с другим числом ячеек (объединённые ячейки) и количество «3 шт.» в одной ячейке читаются без выдумок", () => {
  const text = ["№ | Наименование продукции | Количество", "1 | Электроды УОНИ-13/55, 4 мм | 120 кг", "2 | Маска сварщика | | лишняя ячейка", "3 | Перчатки сварочные | 40 пар."].join("\n");
  const t = findGoodsTable([{ name: "ТЗ.docx", text }]);
  assert.ok(t);
  assert.deepEqual(t.rows, [
    { name: "Электроды УОНИ-13/55, 4 мм", unit: "кг", qty: 120 },
    { name: "Перчатки сварочные", unit: "пар.", qty: 40 },
  ]);
});

// Настоящая закупка лекарства (ГАУЗ «Амурский областной онкологический диспансер», .doc): шапка разорвана на две строки, столбец называется «МНН», в строке данных на ячейку меньше, чем в шапке,
// а «Обоснование НМЦ» — раздел той же документации, а не отдельный файл.
const DRUG = [
  "Документация об электронном аукционе",
  "Раздел 4. Обоснование начальной (максимальной) цены договора",
  "",
  ["№ п/п", "Объект закупки*", "Основные характеристики объекта закупки", "Ед. изм.", "Кол-во", "Источники информации для определения НМЦД", "НМЦД"].join("\t"),
  ["Информация о контракте № 1 от 13.08.2026", "Информация о контракте № 2 от 02.04.2026", "Информация о контракте № 3 от 14.08.2026", "Средний уровень цены"].join("\t"),
  ["цена единицы, руб.", "цена единицы,  руб.", "сумма, руб."].join("\t"),
  ["1", "Дабрафениб", "согласно документации о закупке", "упаковка", "25", "251 130,00", "263 562,20", "266 221,20", "260 304,47", "260 304,47", "6 507 611,75"].join("\t"),
  [" ", "Итого:", " ", " ", " ", " ", " ", " ", " ", " ", "6 507 611,75"].join("\t"),
  "",
  "Раздел 5. Описание предмета закупки (техническое задание / спецификация)",
  "",
  ["№ п/п", "МНН", "Дозировка, лекарственная форма", "Ед."].join("\t"),
  ["изм.", "Количество", "Остаточный срок годности на момент поставки"].join("\t"),
  ["1.", "Дабрафениб ", "75 мг № 120, капсулы ", "упаковка", "25"].join("\t"),
  "Не менее 12 месяцев",
  "",
  "Допускается иное количество единиц в упаковке в пересчете на требуемое количество препарата",
  "",
  "Раздел 6. Инструкция по заполнению заявки на участие.",
  ["№ п/п", "МНН", "Торговое наименование", "дозировка, лекарственная форма", "Ед. изм."].join("\t"),
  "1.",
].join("\n");

test("закупка лекарства из старого .doc: шапка в две строки, столбец «МНН», дозировка и форма — часть названия, количество и упаковка из таблицы; расчёт НМЦ того же документа не мешает", () => {
  const t = findGoodsTable([{ name: "Документация.doc", text: DRUG }]);
  assert.ok(t, "таблица товаров найдена");
  assert.deepEqual(t.rows, [{ name: "Дабрафениб 75 мг № 120, капсулы", unit: "упаковка", qty: 25 }]);
  const found = positionsFromDocuments([{ name: "Документация.doc", text: DRUG }]);
  assert.deepEqual(found?.positions.map((p) => [p.name, p.unit, p.qty]), [["Дабрафениб 75 мг № 120, капсулы", "упаковка", "25"]]);
});

test("отдельный файл «Обоснование НМЦ» по-прежнему не берётся за список товаров участника", () => {
  const text = ["Обоснование начальной (максимальной) цены", ["№", "Объект закупки", "Ед. изм.", "Кол-во", "Цена"].join("\t"), ["1", "Дабрафениб", "упаковка", "25", "260 304,47"].join("\t")].join("\n");
  assert.equal(findGoodsTable([{ name: "Приложение №9 к ДоЗ - ОБОСНОВАНИЕ НМЦ.docx", text }]), null);
  assert.equal(findGoodsTable([{ name: "Расчёт.docx", text }]), null, "по заголовку внутри файла");
});

test("объединённая ячейка, легшая отдельной строкой между позициями, таблицу не обрывает; две такие строки подряд — конец таблицы", () => {
  const text = [
    ["№", "Наименование товара", "Ед. изм.", "Количество"].join("\t"),
    ["1", "Кабель ВВГ 3х2,5", "м", "500"].join("\t"),
    "Применяется только сертифицированный",
    ["2", "Лампа светодиодная", "шт", "40"].join("\t"),
    "Примечание 1",
    "Примечание 2",
    ["3", "Выключатель", "шт", "10"].join("\t"),
  ].join("\n");
  assert.deepEqual(findGoodsTable([{ name: "ТЗ.doc", text }])?.rows.map((r) => r.name), ["Кабель ВВГ 3х2,5", "Лампа светодиодная"]);
});
