// Шаблоны заказчика в документации: какие файлы считаются образцами для заполнения — npm test (без сети, без ИИ).
import assert from "node:assert/strict";
import { test } from "node:test";
import { customerTemplates } from "./customer-templates.ts";

test("находит формы, ценовое предложение и декларацию; договор, извещение, ТЗ и документация шаблонами не считаются", () => {
  const found = customerTemplates([
    { name: "Извещение о закупке.docx", text: "Извещение о проведении закупки. Заказчик: АО «Пример»" },
    { name: "Документация о закупке.pdf", text: "Документация о закупке. Раздел 1. Приложение № 3 — форма заявки." },
    { name: "Техническое задание.docx", text: "Требования к товару." },
    { name: "Проект договора.docx", text: "Договор поставки. Поставщик ___________ обязуется поставить" },
    { name: "Приложение № 3 Форма заявки.docx", text: "ЗАЯВКА НА УЧАСТИЕ\nНаименование участника: ______________\nИНН: ___________\nАдрес: ________________" },
    { name: "Ценовое предложение.docx", text: "Ценовое предложение. Цена: ........... руб." },
    { name: "Декларация о соответствии.docx", text: "Декларация о соответствии участника требованиям. Подпись: ____" },
  ]);
  assert.deepEqual(found.map((t) => [t.name, t.label]), [
    ["Приложение № 3 Форма заявки.docx", "Форма заказчика"],
    ["Ценовое предложение.docx", "Форма цены"],
    ["Декларация о соответствии.docx", "Декларация"],
  ]);
});

test("пустые места: подчёркивания и длинные точки — по числу; без полей — ноль; Excel-бланк помечен", () => {
  const found = customerTemplates([
    { name: "Анкета участника.docx", text: "Анкета\nНаименование: __________\nИНН: _________\nКПП: _________" },
    { name: "Приложение № 5 Спецификация.xlsx", text: "Форма спецификации. Наименование товара | Цена" },
    { name: "Бланк.docx", text: "Бланк. Руководитель: ………………" },
  ]);
  assert.deepEqual(found.map((t) => [t.blanks, t.excel]), [
    [3, false],
    [0, true],
    [1, false],
  ]);
});

test("один и тот же файл дважды показывается один раз; пусто — пустой список", () => {
  assert.equal(
    customerTemplates([
      { name: "Форма заявки.docx", text: "Заявка на участие" },
      { name: "форма заявки.DOCX", text: "Заявка на участие" },
    ]).length,
    1,
  );
  assert.deepEqual(customerTemplates([]), []);
});
