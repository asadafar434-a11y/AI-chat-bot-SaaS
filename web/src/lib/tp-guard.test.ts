// Охрана значений поставщика: граница заказчика не становится предложением участника — npm test.
import assert from "node:assert/strict";
import { test } from "node:test";
import { guardContext, guardOffer, ownConditions } from "./tp-guard.ts";

const TZ = [
  "1.3. Дата и время проведения мероприятия: 27 ноября 2026 г., с 15:00 до 19:00.",
  "2.1. Зал вместимостью не менее 150 мест в пределах г. Энска, с гардеробом.",
  "2.2. Количество участников мероприятия: не менее 120 человек.",
  "3.1. Программа согласовывается с Заказчиком не позднее чем за 10 рабочих дней до даты проведения.",
  "3.4. Ведущий — с опытом проведения официальных мероприятий не менее 3 лет.",
  "3.5. Вокалист и ансамбль в составе не менее 4 музыкантов.",
  "4.1. Звуковое и световое оборудование, светодиодный экран размером не менее 3×2 м, не менее 2 радиомикрофонов.",
  "4.3. Передача Заказчику не менее 100 обработанных фотографий в течение 5 рабочих дней после мероприятия.",
  "5.1. Кофе-брейк на 120 человек: чай, кофе, не менее 2 наименований выпечки на человека.",
  "Ширина ленты: не менее 15 мм и не более 16 мм.",
  "Количество: 200 шт.",
].join("\n");
const ctx = guardContext([TZ]);
const guard = (offer: string, quote: string, requirement = "") => guardOffer(offer, ownConditions(quote, requirement), ctx);

test("число с границы заказчика — не значение участника: на его месте пустое место с границей в подсказке", () => {
  const people = guard("Обеспечим проведение мероприятия для 120 участников.", "Количество участников мероприятия: не менее 120 человек.");
  assert.equal(people.text, "Обеспечим проведение мероприятия для [число, не меньше 120] участников.");
  assert.deepEqual(people.hits.map((h) => h.hint), ["[число, не меньше 120]"]);

  const band = guard("Выступит ансамбль из 4 музыкантов.", "Вокалист и ансамбль в составе не менее 4 музыкантов.");
  assert.equal(band.text, "Выступит ансамбль из [число, не меньше 4] музыкантов.");

  const staff = guard("Ведущий с опытом 3 года.", "Ведущий мероприятия — с опытом проведения официальных мероприятий не менее 3 лет.");
  assert.equal(staff.text, "Ведущий с опытом [число, не меньше 3] года.");
});

test("значение, которого заказчик не называл, но с той же единицей, — придумано: тоже пустое место", () => {
  // «Не менее 100 фотографий» — ИИ написал 120: это не граница, а выдумка, и она тоже не должна попасть в заявку.
  const photos = guard(
    "Передадим Заказчику 120 обработанных фотографий в течение 5 рабочих дней после мероприятия.",
    "Передача Заказчику не менее 100 обработанных фотографий в течение 5 рабочих дней после мероприятия."
  );
  assert.equal(photos.text, "Передадим Заказчику [число, не меньше 100] обработанных фотографий в течение 5 рабочих дней после мероприятия.");

  const hall = guard("Предоставим зал на 200 мест.", "Зал вместимостью не менее 150 мест в пределах г. Энска.");
  assert.equal(hall.text, "Предоставим зал на [число, не меньше 150] мест.");
});

test("размеры: «4×2,5 м» к «не менее 3×2 м» заменяются целиком", () => {
  const screen = guard(
    "Предоставим светодиодный экран размером 4×2,5 м, 2 радиомикрофона.",
    "Звуковое и световое оборудование, светодиодный экран размером не менее 3×2 м, не менее 2 радиомикрофонов."
  );
  assert.equal(screen.text, "Предоставим светодиодный экран размером [размер, не меньше 3×2] м, [число, не меньше 2] радиомикрофона.");
});

test("диапазон заказчика: значение внутри диапазона — тоже решение участника", () => {
  const tape = guard("Ширина ленты: 15,5 мм.", "Ширина ленты: не менее 15 мм и не более 16 мм.");
  assert.equal(tape.text, "Ширина ленты: [число, от 15 до 16] мм.");
});

test("не трогаются даты, время, сроки заказчика, точные значения заказчика и номера пунктов", () => {
  const untouched = [
    ["Проведём мероприятие 27 ноября 2026 г. с 15:00 до 19:00.", "Дата и время проведения мероприятия: 27 ноября 2026 г., с 15:00 до 19:00."],
    ["Согласуем программу не позднее чем за 10 рабочих дней до даты проведения.", "Программа согласовывается не позднее чем за 10 рабочих дней до даты проведения."],
    ["Организуем кофе-брейк на 120 человек: чай, кофе.", "Кофе-брейк на 120 человек: чай, кофе, не менее 2 наименований выпечки на человека."],
    ["Поставим 200 шт. в соответствии с п. 2.1 ТЗ.", "Количество: 200 шт."],
    ["Обеспечим зал на [число, не меньше 150] мест.", "Зал вместимостью не менее 150 мест."],
  ] as const;
  for (const [offer, quote] of untouched) assert.equal(guard(offer, quote).text, offer, offer);
  // А число рядом с «не менее» в том же предложении — по-прежнему граница.
  const mixed = guard("Организуем кофе-брейк на 120 человек: чай, кофе, 2 наименования выпечки на человека.", "Кофе-брейк на 120 человек: чай, кофе, не менее 2 наименований выпечки на человека.");
  assert.equal(mixed.text, "Организуем кофе-брейк на 120 человек: чай, кофе, [число, не меньше 2] наименования выпечки на человека.");
});

test("слова заказчика «не менее» в предложении уходят вместе с числом: граница — в подсказке", () => {
  const wording = guard("Зал вместимостью не менее 150 мест.", "Зал вместимостью не менее 150 мест.");
  assert.equal(wording.text, "Зал вместимостью [число, не меньше 150] мест.");
});

test("другая величина с тем же числом — не граница: «5 кг» при «не менее 5 дней»", () => {
  const other = guard("Вес набора — 5 кг.", "Срок хранения не менее 5 дней.");
  assert.equal(other.text, "Вес набора — 5 кг.");
});

test("несколько разных границ с одной единицей: берётся та, в которую число попадает; не ясно какая — место без границы, а не чужая граница", () => {
  const ctxTape = guardContext(["Длина: не менее 25 см и не более 26 см. Ширина: не менее 1,9 см и не более 2 см. Высота: не менее 12 см и не более 14 см."]);
  const own = ownConditions("Длина: не менее 25 см и не более 26 см. Ширина: не менее 1,9 см и не более 2 см.");
  // 1,95 см попадает только в «ширину».
  assert.equal(guardOffer("Ширина — 1,95 см.", own, ctxTape).text, "Ширина — [число, от 1,9 до 2] см.");
  // 40 см не попадает ни в одну из границ пункта — какая из двух имеется в виду, неизвестно: граница не называется.
  const lost = guardOffer("Длина — 40 см.", own, ctxTape);
  assert.equal(lost.text, "Длина — [число] см.");
  assert.equal(lost.hits[0].bound, "", "граница не названа: проверять вписанное по ней нельзя");
  // Границы нет у пункта, а в закупке их несколько разных — тоже без границы.
  assert.equal(guardOffer("Высота — 13 см.", [], ctxTape).text, "Высота — [число] см.");
  assert.equal(guardOffer("Высота — 13,5×4 см.", [], ctxTape).text, "Высота — [размер] см.");
  // Одна и та же граница, повторённая в разных пунктах, — не неоднозначность.
  const same = guardContext(["Специалист: опыт не менее 2 лет. Другой специалист: опыт не менее 2 лет. Третий: опыт не менее 2 лет."]);
  assert.equal(guardOffer("Опыт работы — 5 лет.", [], same).text, "Опыт работы — [число, не меньше 2] лет.");
});

test("в находке сказано, какая граница заказчика заменена", () => {
  const found = guard("Обеспечим для 120 участников.", "Количество участников: не менее 120 человек.");
  assert.deepEqual(found.hits.map((h) => [h.value, h.hint, h.bound]), [["120", "[число, не меньше 120]", "не менее 120 человек"]]);
});

test("характеристики товара: строка за строкой, как их пишет ИИ", () => {
  const ctxGoods = guardContext(["Мощность | не менее 40 | кВт\nМасса | не более 5 | кг\nНапряжение | 220 | В"]);
  const goods = guardOffer("Мощность: 40 кВт\nМасса: 4,5 кг\nНапряжение: 220 В", ownConditions("Мощность | не менее 40 | кВт"), ctxGoods);
  assert.equal(goods.text, "Мощность: [число, не меньше 40] кВт\nМасса: [число, не больше 5] кг\nНапряжение: 220 В");
  assert.equal(goods.hits.length, 2);
});

test("без границ в закупке предложение не меняется; пустой текст — тоже", () => {
  const empty = guardContext(["Поставка бумаги. Количество: 500 листов."]);
  assert.equal(guardOffer("Поставим 500 листов бумаги", [], empty).text, "Поставим 500 листов бумаги");
  assert.equal(guardOffer("", [], ctx).text, "");
});

test("охрана идемпотентна: уже подготовленное предложение второй раз не меняется", () => {
  const once = guard("Обеспечим 120 участников и зал на 200 мест.", "Количество участников: не менее 120 человек. Зал не менее 150 мест.");
  const twice = guardOffer(once.text, ownConditions("Количество участников: не менее 120 человек. Зал не менее 150 мест."), ctx);
  assert.equal(twice.text, once.text);
  assert.equal(twice.hits.length, 0);
});
