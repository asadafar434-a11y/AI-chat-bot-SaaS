// Основа рыночной цены в продукте — закупочная цена: за сколько участник может купить товар (прайс производителя или оптового поставщика, коммерческое предложение, биржевая котировка).
// Цена заключённого контракта (реестр контрактов ЕИС, цена победителя на торгах) в рыночную цену не идёт: в ней уже есть маржа поставщика, а участнику нужно знать, сколько товар стоит ему самому
// (решение владельца 22.10.2026: «в контракте цена уже с маржой поставщика, а нам рыночная нужна»; «везде так строго»).
// Правило едино для базы цен (lib/market-observations.ts) и расчёта РИЦ (lib/indicative-price.ts). Модуль без зависимостей: его проверяют тесты (npm test).

/** Почему цена не принимается: показывается там, где цена отклонена. */
export const CONTRACT_PRICE_REASON = "цена контракта — в ней маржа победителя; нужна закупочная цена (прайс, коммерческое предложение, биржа)";

const CONTRACT_SOURCE = [
  /^\s*ЕИС(?![а-яёa-z0-9])/i,
  /реестр[а-я]*\s+контракт/i,
  /контракт\s*(№|n\b|номер)/i,
  /(?<!\d)\d{19}(?!\d)/,
  /протокол\s+(подведения|итогов)/i,
  /zakupki\.gov\.ru/i,
];

/** Источник цены — заключённый контракт или итоги торгов: такая цена с маржой поставщика и закупочной не считается. */
export const isContractPriceSource = (source: string): boolean => CONTRACT_SOURCE.some((re) => re.test(String(source ?? "")));
