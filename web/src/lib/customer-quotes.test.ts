import assert from "node:assert/strict";
import { test } from "node:test";
import { findCustomerQuotes, quoteBasis, quotesFinding } from "./customer-quotes.ts";

// «Приложение № 9. Обоснование НМЦ» к закупке «Поставка сварочных агрегатов» (АО «ДГК», 23.10.2026): таблица читается из Word строками «а | б | в».
const APPENDIX_9 = [
  "обоснование НМЦ",
  "",
  "1.3. | НМЦ | 9 305 651,64 рублей без учета НДС",
  "",
  "Метод анализа технико-коммерческих предложений",
  "",
  "Наименование товара/ работы/ услуги в составе лота | Наименование источника ценовой информации (ИЦИ) | Цена с учетом полученной информации из соответствующего ИЦИ, в руб. без НДС | Цена итоговая, в руб. без НДС | Комментарии",
  'ОКПД2: 28.29.70.110 Поставка сварочных агрегатов для нужд АО "ДГК" | Поставка сварочных агрегатов, ТКП №1 | 9 305 651,64 | Минимальное значение полученных ТКП: 9 305 651,64 | Мониторинг на ЭТП RH21092600003',
  " | Поставка сварочных агрегатов, ТКП №2 | 9 377 049,18",
  " | Поставка сварочных агрегатов, ТКП №3 | 9 581 967,21",
  "",
  "Сноски",
].join("\n");

test("три предложения поставщиков из обоснования НМЦ: цены, разброс 3 %, без НДС", () => {
  const q = findCustomerQuotes([{ name: "Приложение №9 к ДоЗ - ОБОСНОВАНИЕ НМЦ.docx", text: APPENDIX_9 }]);
  assert.ok(q);
  assert.deepEqual(q.quotes.map((x) => [x.label, x.price]), [["ТКП №1", 9305651.64], ["ТКП №2", 9377049.18], ["ТКП №3", 9581967.21]]);
  assert.equal(q.min, 9305651.64);
  assert.equal(q.max, 9581967.21);
  assert.equal(Math.round(q.spreadPct * 10) / 10, 3);
  assert.equal(q.vat, "without");
});

test("начальная цена равна минимальному предложению — определяется по числам, а не по словам", () => {
  const q = findCustomerQuotes([{ name: "a", text: APPENDIX_9 }])!;
  assert.equal(quoteBasis(q, 9305651.64), "min");
  assert.equal(quoteBasis(q, 9581967.21), "max");
  assert.equal(quoteBasis(q, 9400000), null, "не совпало ни с одним — ничего не утверждаем");
  assert.equal(quoteBasis(q, null), null);
  const line = quotesFinding(q, 9305651.64);
  assert.match(line.text.replace(/[  ]/g, " "), /3 предложения: от 9 305 651,64 ₽ до 9 581 967,21 ₽, разброс 3,0 %; начальная цена взята по минимальному предложению/);
  assert.match(line.text, /не ваша себестоимость/);
  assert.doesNotMatch(quotesFinding(q, 9400000).text, /начальная цена/);
});

test("не предложения: одно предложение, слова без номера, мелкие числа и повтор номеров в другой таблице", () => {
  assert.equal(findCustomerQuotes([{ name: "a", text: "Источник | Цена\nТКП №1 | 9 305 651,64" }]), null, "одно предложение — разброса нет");
  assert.equal(findCustomerQuotes([{ name: "a", text: "Источник | Цена\nМинимальное значение полученных ТКП | 9 305 651,64\nКоммерческое предложение | 9 377 049,18" }]), null, "без номера это не строки предложений");
  assert.equal(findCustomerQuotes([{ name: "a", text: "Источник | Количество\nТКП №1 | 2\nТКП №2 | 3" }]), null, "числа меньше 100 — не цены");
  const two = findCustomerQuotes([
    { name: "a", text: "Позиция 1 | КП №1 | 1 000,00\nПозиция 1 | КП №2 | 1 200,00\n\nПозиция 2 | КП №1 | 50 000,00\nПозиция 2 | КП №2 | 60 000,00" },
  ]);
  assert.deepEqual(two?.quotes.map((x) => x.price), [1000, 1200], "вторая таблица с теми же номерами не смешивается с первой");
});

test("«коммерческое предложение №2» и цена с «руб.» читаются; цена с НДС отмечается", () => {
  const q = findCustomerQuotes([{ name: "a", text: "Поставщик | Цена с учетом НДС\nКоммерческое предложение №1 | 120 000 руб.\nКоммерческое предложение №2 | 130 000,50 ₽" }]);
  assert.ok(q);
  assert.deepEqual(q.quotes.map((x) => [x.label, x.price]), [["КП №1", 120000], ["КП №2", 130000.5]]);
  assert.equal(q.vat, "with");
});
