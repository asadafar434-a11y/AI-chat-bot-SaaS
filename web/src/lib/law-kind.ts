// Закон и способ закупки — из строки «44-ФЗ · электронный аукцион», как её выписал разбор документов (lib/requirements.ts).
// От закона зависит, что участник кладёт в заявку сам, а что за него передаёт площадка (lib/fulfillment.ts).

export type Law = "44" | "223";

export const lawOfKind = (kind = ""): Law | null => (/(?<!\d)(44|223)-ФЗ/.exec(kind)?.[1] as Law | undefined) ?? null;

// Электронная процедура. По 44-ФЗ на бумаге подают только в закрытых конкурсе и аукционе (ч. 7 ст. 43),
// остальные способы — электронные.
export const isElectronic = (kind = "") => /электрон/i.test(kind) || !/закрыт/i.test(kind);

// Сведения об участнике — наименование, ИНН, КПП, адрес, руководитель, выписка из ЕГРЮЛ — по 44-ФЗ в электронной
// процедуре участник в заявку не включает: их передаёт площадка из ЕИС (п. 2 ч. 6 ст. 43 44-ФЗ). Анкета не нужна.
// В 223-ФЗ такого правила нет: анкету подают, если её требует документация закупки.
export const participantFromPlatform = (kind = "") => lawOfKind(kind) === "44" && isElectronic(kind);

export const isAuction = (kind = "") => /аукцион/i.test(kind);

// Вводный абзац шага «Цена». Про торги и статью 49 — только там, где они есть: в запросе котировок, конкурсе и закупках по 223-ФЗ
// цену называют в заявке, торгов нет, а статья 49 44-ФЗ — об аукционе.
export function priceIntro(kind = ""): string {
  const tail = "Расчёт по вашим расходам, без ИИ.";
  if (isAuction(kind)) {
    const law = lawOfKind(kind) === "44" ? " (ч. 2 ст. 49 44-ФЗ)" : "";
    return `На аукционе цену подают во время торгов${law}. Здесь — до какой цены можно снижаться, чтобы контракт не ушёл в убыток. ${tail}`;
  }
  return `Цену вы указываете в заявке. Здесь — ниже какой цены не стоит опускаться, чтобы контракт не ушёл в убыток. ${tail}`;
}

// Пояснение на шаге «Анализ», почему сведений об участнике (наименование, ИНН, адрес) в заявке нет; null — пояснение не нужно.
export function platformNote(kind = ""): string | null {
  if (!participantFromPlatform(kind)) return null;
  if (isAuction(kind)) {
    return "Наименование, ИНН и адрес в заявку на аукцион не пишут: по ч. 1 ст. 49 44-ФЗ заявка содержит сведения из пп. «м»–«п» п. 1, пп. «а»–«в» п. 2 и п. 5 ч. 1 ст. 43, остальное площадка передаёт сама.";
  }
  return "Наименование, ИНН и адрес в заявку не пишут: по п. 2 ч. 6 ст. 43 44-ФЗ эти сведения в электронной процедуре передаёт площадка.";
}
