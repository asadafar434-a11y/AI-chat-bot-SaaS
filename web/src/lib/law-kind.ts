// Закон и способ закупки — из строки «44-ФЗ · электронный аукцион», как её выписал разбор документов (lib/requirements.ts).
// От закона зависит, что участник кладёт в заявку сам, а что за него передаёт площадка (lib/fulfillment.ts).

export type Law = "44" | "223";

export const lawOfKind = (kind = ""): Law | null => (/(?<!\d)(44|223)-ФЗ/.exec(kind)?.[1] as Law | undefined) ?? null;

// Электронная процедура. По 44-ФЗ на бумаге подают только в закрытых конкурсе и аукционе (ч. 7 ст. 43),
// остальные способы — электронные.
export const isElectronic = (kind = "") => /электрон/i.test(kind) || !/закрыт/i.test(kind);

// Сведения об участнике — наименование, ИНН, КПП, адрес, руководитель, выписка из ЕГРЮЛ — по 44-ФЗ в электронной
// процедуре участник в заявку не включает: их передаёт площадка из ЕИС (п. 2 ч. 6 ст. 43 44-ФЗ). Анкета не нужна.
// В 223-ФЗ такого правила нет: анкету подают, если её требует документация закупки.
export const participantFromPlatform = (kind = "") => lawOfKind(kind) === "44" && isElectronic(kind);

export const isAuction = (kind = "") => /аукцион/i.test(kind);

// Закупка у единственного поставщика: заявки нет — заказчик заключает договор с названным поставщиком и сам называет цену, торгов нет.
export const isSingleSupplier = (kind = "") => /единственн[а-яё]*\s+(поставщик|подрядчик|исполнител)/i.test(kind);

// Есть ли в закупке заявка участника. У единственного поставщика её нет: техническое предложение, анкета и цена в заявку не составляются.
export const hasApplication = (kind = "") => !isSingleSupplier(kind);

// Неконкурентная закупка среди субъектов МСП (ПП РФ № 1352, п. 20(1)): участник подаёт на площадке «предварительное предложение»,
// а что в нём должно быть, пишет извещение. Это не конкурентная закупка только для МСП: закрытый перечень документов ч. 19.1 ст. 3.4 223-ФЗ
// здесь не применяется, основание пунктов — извещение (fulfillment.ts). «У единственного поставщика» сюда не входит: там заявки нет.
export const isNoncompetitiveSme = (kind = "") =>
  /неконкурентн/i.test(kind) && (/(?<![а-яё])(?:МСП|СМСП)(?![а-яё])/i.test(kind) || /субъект[а-яё]*\s+мал/i.test(kind));

// Вводный абзац шага «Цена». Про торги и статью 49 — только там, где они есть: в запросе котировок, конкурсе и закупках по 223-ФЗ
// цену называют в заявке, торгов нет, а статья 49 44-ФЗ — об аукционе.
export function priceIntro(kind = ""): string {
  const tail = "Расчёт по вашим расходам, без ИИ.";
  if (isSingleSupplier(kind)) {
    return `Цену называет заказчик: торгов и заявки нет. Здесь — сверьте её со своими расходами: что останется вам при цене заказчика. ${tail}`;
  }
  if (isNoncompetitiveSme(kind)) {
    return `Цену вы указываете в предварительном предложении на площадке. Здесь — ниже какой цены не стоит опускаться, чтобы договор не ушёл в убыток. ${tail}`;
  }
  if (isAuction(kind)) {
    const law = lawOfKind(kind) === "44" ? " (ч. 2 ст. 49 44-ФЗ)" : "";
    return `На аукционе цену подают во время торгов${law}. Здесь — до какой цены можно снижаться, чтобы контракт не ушёл в убыток. ${tail}`;
  }
  return `Цену вы указываете в заявке. Здесь — ниже какой цены не стоит опускаться, чтобы контракт не ушёл в убыток. ${tail}`;
}

// Пояснение на шаге «Анализ»: почему сведений об участнике (наименование, ИНН, адрес) в заявке нет, почему нет самой заявки (у единственного
// поставщика) и что делать, если в документах не назван закон; null — пояснение не нужно.
export function platformNote(kind = ""): string | null {
  const notes: string[] = [];
  if (isSingleSupplier(kind)) {
    notes.push(
      "Закупка у единственного поставщика: заявку не подают, документы заявки приложение не составляет. Заказчик заключает договор с названным поставщиком — подготовьте то, что просит извещение.",
    );
  }
  if (kind.trim() && lawOfKind(kind) === null) {
    notes.push(
      "В документах не назван закон — 44-ФЗ или 223-ФЗ, поэтому основанием пунктов названы документы закупки. Государственные и муниципальные унитарные предприятия и госкомпании закупают по 223-ФЗ; если сомневаетесь — уточните у заказчика.",
    );
  }
  if (participantFromPlatform(kind)) {
    notes.push(
      isAuction(kind)
        ? "Наименование, ИНН и адрес в заявку на аукцион не пишут: по ч. 1 ст. 49 44-ФЗ заявка содержит сведения из пп. «м»–«п» п. 1, пп. «а»–«в» п. 2 и п. 5 ч. 1 ст. 43, остальное площадка передаёт сама."
        : "Наименование, ИНН и адрес в заявку не пишут: по п. 2 ч. 6 ст. 43 44-ФЗ эти сведения в электронной процедуре передаёт площадка.",
    );
  }
  return notes.length > 0 ? notes.join(" ") : null;
}
