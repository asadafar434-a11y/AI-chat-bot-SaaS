// Закон и способ закупки — из строки «44-ФЗ · электронный аукцион», как её выписал разбор документов (lib/requirements.ts).
// От закона зависит, что участник кладёт в заявку сам, а что за него передаёт площадка (lib/fulfillment.ts).

export type Law = "44" | "223";

export const lawOfKind = (kind = ""): Law | null => (/(?<!\d)(44|223)-ФЗ/.exec(kind)?.[1] as Law | undefined) ?? null;

// Электронная процедура. По 44-ФЗ на бумаге подают только в закрытых конкурсе и аукционе (ч. 7 ст. 43),
// остальные способы — электронные.
export const isElectronic = (kind = "") => /электрон/i.test(kind) || !/закрыт/i.test(kind);

// Сведения об участнике — наименование, ИНН, КПП, адрес, руководитель, выписка из ЕГРЮЛ — по 44-ФЗ в электронной
// процедуре участник в заявку не включает: их передаёт площадка из ЕИС (п. 2 ч. 6 ст. 43 44-ФЗ). Анкета не нужна.
// В 223-ФЗ такого правила нет: анкету подают, если её требует документация закупки.
export const participantFromPlatform = (kind = "") => lawOfKind(kind) === "44" && isElectronic(kind);
