// Без ИИ раскладываем по словам в названии файла и в начале текста — хуже, но лучше, чем ничего.
const GUESS: [RegExp, DocKind][] = [
  [/техническ\S* предложени|предложени\S* участника|в отношении объекта закупки/i, "tp"],
  [/анкет|сведения об участнике/i, "anketa"],
  [/декларац/i, "declaration"],
  [/предложени\S* о цене|ценов\S* предложени|коммерческ\S* предложени/i, "price"],
  [/заявк\S* на участие|опись/i, "letter"],
  [/карточк\S* (предприятия|организации|компании|контрагента)|выписк\S* из ЕГР|устав|лиценз|доверенност/i, "company"],
  [/исполненн\S* (договор|контракт)|акт\S* (о приёмке|о приемке|приёмки|приемки|оказанных услуг|выполненных работ)|реестр\S* контрактов/i, "experience"],
  [/диплом|удостоверени|повышени\S* квалификации|трудов\S* (договор|книжк)|электробезопасност|допуск\S* к работ/i, "staff"],
];

export function guessKinds(name: string, text: string): DocKind[] {
  const probe = `${name}\n${text.slice(0, 1500)}`;
  const kinds = GUESS.filter(([re]) => re.test(probe)).map(([, kind]) => kind);
  return kinds.length ? [...new Set(kinds)] : ["other"];
}

