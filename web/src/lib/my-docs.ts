// Реквизиты из документов участника. quote — чтобы проверить, что значение не придумано.
export const ProfileFoundSchema = z.object({
  fields: z.array(
    z.object({
      key: z.enum(PROFILE_KEYS as [ProfileKey, ...ProfileKey[]]),
      value: z.string().describe("Значение поля в том виде, в каком его пишут в заявке"),
      source: z.string().describe("Название документа, из которого взято значение, как в заголовке блока"),
      quote: z.string().describe("Дословный фрагмент этого документа, в котором есть значение"),
    })
  ),
  conflicts: z
    .array(
      z.object({
        key: z.enum(PROFILE_KEYS as [ProfileKey, ...ProfileKey[]]),
        value: z.string(),
        source: z.string(),
      })
    )
    .describe("Другие значения тех же полей из других документов, если они отличаются от выбранных; пустой список, если расхождений нет"),
});

export type FoundField = { key: ProfileKey; value: string; source: string };
export type ProfileFound = { fields: FoundField[]; conflicts: FoundField[] };

