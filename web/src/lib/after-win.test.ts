// «Что потребуется после победы»: обязанности подрядчика из проекта договора со сроком или периодичностью — npm test (без ИИ).
import assert from "node:assert/strict";
import { test } from "node:test";
import { afterWinDuties, isContract } from "./after-win.ts";

const contract = (...lines: string[]) => [{ name: "Приложение № 4 Проект договора.doc", text: lines.join("\n") }];

test("срок «в течение 10 календарных дней с момента заключения» и периодичность («ежеквартально», «каждый вторник») попадают в список", () => {
  const result = afterWinDuties(
    contract(
      "5.22. Подрядчик должен в течение 10 календарных дней с момента заключения договора предоставить в налоговый орган Согласие. В самом Согласии должен быть указан срок.",
      "5.24. Подрядчик ежеквартально предоставляет информацию о численности сотрудников с приложением подтверждающих документов.",
      "5.26. Подрядчик каждый вторник с нарастающим итогом предоставляет Заказчику информацию по выполненным видам работ.",
    ),
  )!;
  assert.deepEqual(
    result.duties.map((d) => [d.clause, d.term]),
    [
      ["5.22", "в течение 10 календарных дней с момента заключения договора"],
      ["5.24", "ежеквартально"],
      ["5.26", "каждый вторник"],
    ],
  );
  assert.equal(result.more, null);
});

test("обязанности без срока считаются вместе: «ещё N … п. 5.14–5.16»", () => {
  const result = afterWinDuties(
    contract(
      "5.14. Подрядчик обязан предоставить список сотрудников подрядной организации.",
      "5.15. Подрядчик обязан предоставить заверенные копии приказов о приёме на работу.",
      "5.16. Подрядчик обязан предоставить заверенные копии журналов инструктажа.",
      "5.24. Подрядчик ежеквартально предоставляет информацию о численности.",
    ),
  )!;
  assert.equal(result.duties.length, 1);
  assert.deepEqual(result.more, { count: 3, range: "п. 5.14–5.16" });
});

test("не обязанности подрядчика: заказчик, расчёты, смена реквизитов, срок «до подачи заявки», чужой документ", () => {
  assert.equal(
    afterWinDuties(
      contract(
        "6.1. Заказчик обязан в течение 5 рабочих дней предоставить Подрядчику доступ на объект.",
        "7.1.2. Подрядчик за 3 рабочих дня до приемки предоставляет Заказчику акты КС-2 и справки КС-3.",
        "3.5. В течение одного рабочего дня Подрядчик сообщает Заказчику об изменении банковских реквизитов, смене руководителя и иных сведений.",
        "4.1. В течение 2 календарных дней с даты окончания услуг Исполнитель предоставляет Заказчику Отчетную документацию и Документ о приемке.",
        "9.1. Участник, с которым заключается договор, не привлекался в течение трёх лет до даты подачи заявки; Подрядчик предоставляет справку.",
      ),
    ),
    null,
  );
  // Не договор — извещение со словами «предоставить в течение 3 дней» — не читаем.
  assert.equal(afterWinDuties([{ name: "Извещение.docx", text: "5.1. Подрядчик должен в течение 3 дней предоставить список." }]), null);
});

test("одна слабая обязанность без срока («по запросу») список не открывает", () => {
  assert.equal(afterWinDuties(contract("5.1.27. Исполнитель обязуется предоставлять по запросу Заказчика информацию и документы о качестве.")), null);
});

test("договор узнаётся по названию файла или по первой строке", () => {
  assert.equal(isContract({ name: "Проект контракта.docx", text: "" }), true);
  assert.equal(isContract({ name: "Приложение 4.docx", text: "ДОГОВОР №\nна выполнение работ" }), true);
  assert.equal(isContract({ name: "Извещение.docx", text: "Извещение о закупке" }), false);
});

test("длинное предложение сокращается; больше шести обязанностей со сроком — остальные уходят в «ещё»", () => {
  const lines = Array.from({ length: 8 }, (_, i) => `5.${30 + i}. Подрядчик ежемесячно предоставляет справку ${"о численности ".repeat(i === 0 ? 30 : 1)}.`);
  const result = afterWinDuties(contract(...lines))!;
  assert.equal(result.duties.length, 6);
  assert.ok(result.duties[0].text.length <= 230 && result.duties[0].text.endsWith("…"));
  assert.deepEqual(result.more, { count: 2, range: "п. 5.36–5.37" });
});

test("в договоре сторона называется «Покупатель»: его обязанности («Покупатель обязан … предоставлять Поставщику Заявку») — не обязанности поставщика", () => {
  assert.equal(
    afterWinDuties(
      contract(
        "2.3.1. Ежемесячно, не позднее 10 числа месяца, предшествующего месяцу поставки, предоставлять Поставщику для согласования Заявку, содержащую сведения о количестве.",
        "2.3.4. Покупатель обязан не позднее 5 дней сообщать Поставщику информацию о реорганизации.",
      ),
    ),
    null,
  );
  // А когда подрядчик назван раньше глагола — это его обязанность, даже если Покупатель назван дальше.
  const result = afterWinDuties(contract("2.1.3. Поставщик ежемесячно, не позднее 5 числа, направляет Покупателю список отгруженных партий.", "2.1.4. Поставщик ежеквартально предоставляет Покупателю отчёт о качестве."))!;
  assert.deepEqual(result.duties.map((d) => d.clause), ["2.1.3", "2.1.4"]);
});
