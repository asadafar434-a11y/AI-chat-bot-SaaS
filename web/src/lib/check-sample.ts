// Цитаты примера сверяются тем же кодом, что и ответы модели.
export function sampleCheck(): CheckResult {
  const docs = SAMPLE_DOCUMENTS.map((d) => d.text);
  return {
    findings: FINDINGS.map((f) => ({
      ...f,
      verified: !f.quote || quoteFound(f.quote, docs),
      appVerified: !f.inApplication || quoteFound(f.inApplication, [SAMPLE_APPLICATION.text]),
    })),
    okCount: 10,
    files: [SAMPLE_APPLICATION.name],
    docsKey: docsKeyOf(SAMPLE_DOCUMENTS.map((d) => d.name)),
    checkedAt: new Date().toISOString(),
  };
}
