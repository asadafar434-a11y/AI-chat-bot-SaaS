test("в наборе восемь документов, главного документа («Информационная карта») и извещения нет", () => {
  assert.deepEqual(readdirSync(DIR).filter((n) => !n.endsWith(".md")).sort(), [...FILES].sort());
  assert.ok(!readdirSync(DIR).some((n) => /информационн|извещени/i.test(n)));
});

test("обоснование НМЦД (.xls): метод рыночных цен, 2 900 т × 8 941,38 ₽ = 25 930 002,00 ₽ без НДС, коэффициент вариации 10 %", async () => {
  const t = await read(GROUNDS);
  assert.match(t, /Метод сопоставимых рыночных цен/);
  assert.match(t, /Поставка угля \| 2900 \| 3 \| 8941,38 \| 9835,52 \| 8047,24 \| 8941,38 \| 894,14 \| 10,0000\d+ \| 259300\d+/);
  const offers = [8941.38, 9835.52, 8047.24];
  const mean = offers.reduce((a, b) => a + b, 0) / 3;
  assert.equal(Math.round(mean * 100), 894138);
  const sd = Math.sqrt(offers.reduce((s, x) => s + (x - mean) ** 2, 0) / 2);
  assert.equal(Math.round(sd * 100), 89414);
  assert.equal(Math.round((sd / mean) * 100), 10);
  assert.equal(Math.round(2900 * 8941.38 * 100), 2_593_000_200);
});

