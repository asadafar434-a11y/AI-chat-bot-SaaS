// Скрытое в файлах заявки: лист Excel, строки и столбцы, скрытый текст Word. Некоторые заказчики это запрещают («Применение в электронных
// документах скрытых листов, столбцов, строк, текста и тому подобного не допускается»). Предупреждаем только тогда, когда запрет есть
// в документах закупки, — иначе скрытое участнику не мешает и лишнего не показываем. Модуль без зависимостей от браузера и сервера.

type Doc = { name: string; text: string };

// «скрытых листов … не допускается», «не допускается … скрытых листов», «запрещены скрытые столбцы».
const FORBID =
  /скрыт[а-яё]*\s+(?:лист|столб|строк|текст)(?:[^.]|т\.\s?п\.){0,120}не\s+допуска|не\s+допуска(?:[^.]|т\.\s?п\.){0,120}скрыт[а-яё]*\s+(?:лист|столб|строк|текст)|запрещ[а-яё]*(?:[^.]|т\.\s?п\.){0,80}скрыт[а-яё]*\s+(?:лист|столб|строк|текст)/i;

export const forbidsHidden = (customerDocs: { text: string }[]) => customerDocs.some((d) => FORBID.test(d.text));

export function hiddenWarning(own: { name: string; hidden?: string[] }[], customerDocs: Doc[]): string | null {
  const files = own.filter((d) => d.hidden && d.hidden.length > 0);
  if (files.length === 0 || !forbidsHidden(customerDocs)) return null;
  const list = files.map((d) => `«${d.name}» — ${d.hidden!.join("; ")}`).join(". ");
  return `Заказчик не допускает в файлах заявки скрытые листы, столбцы, строки и текст, а в них они есть: ${list}. Покажите или удалите их.`;
}
