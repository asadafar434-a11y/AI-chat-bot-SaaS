import assert from "node:assert/strict";
import { test } from "node:test";
import { findResourceNeed, termMonths } from "./resource-need.ts";

// Куски настоящей «Проектно-технической документации» по тендеру на услуги 3PL-оператора (склад в Торжке, 2025–2026).
const THREE_PL = [
  "Срок оказания услуг: услуги оказываются в течении 24 месяцев с момента подписания договора (срок оказания услуг – с «01» января 2025 г. по «31» декабря 2026 г.)",
  "",
  "1.4. Требования к персоналу:",
  "",
  "Минимальное необходимое количество персонала:",
  "",
  "Должность | Квалификация / опыт работы | Количество человек",
  "Руководитель | Не менее 5 лет | 1",
  "Клиентский менеджер | Не менее 3 лет | 1",
  "Старший оператор | Не менее 3 лет | 1",
  "Кладовщик КРО | Не менее 3 лет | 1",
  "Старший смены | Не менее 3 лет | 4",
  "Диспетчер по транспорту | Не менее 3 лет | 2",
  "Специалист по транспортной безопасности | Не менее 3 лет | 2",
  "Оператор склада | Не менее 3 лет | 7",
  "Кладовщик | Не менее 3 лет | 6",
  "Водитель штабелера | Не менее 3 лет | 20",
  "Комплектовщик | Не менее 3 лет | 8",
  "ИТОГО |  | 53",
  "",
  "1.5. Требования к технике",
  "",
  "Минимальное необходимое количество техники:",
  "",
  "Наименование | Кол-во единиц | Грузоподъемность, кг | Высота мачты, см | АКБ (основные) | АКБ (запас)",
  "Ричтрак | 10 |  |  | 10 | 10",
  "из них | 8 | 1400 | 10050",
  "из них | 2 | 1600 | 10050",
  "Погрузчик | 7 |  |  | 7 | 7",
  "из них | 5 | 1300 | 3590",
  "из них | 2 | 1500 | 3590",
  "Паллетоперевозчик электрический самоходный | 2 | 2000 |  | 2 | 2",
  "Гидравлическая тележка (рохля) | 6 | 1500",
  "Итого: | 25",
].join("\n");

test("персонал и техника из таблиц заказчика: 11 должностей на 53 человека, 4 вида техники на 25 единиц, срок 24 месяца; «из них» и «Итого» не считаются", () => {
  const need = findResourceNeed([{ name: "Проектно-техническая документация.docx", text: THREE_PL }]);
  assert.ok(need);
  assert.equal(need.staff.length, 11);
  assert.equal(need.staff.reduce((s, r) => s + r.count, 0), 53, "сходится с «ИТОГО 53» заказчика");
  assert.deepEqual(need.staff.find((r) => r.role === "Водитель штабелера"), { role: "Водитель штабелера", count: 20, requirement: "Не менее 3 лет" });
  assert.deepEqual(need.equipment, [
    { name: "Ричтрак", count: 10 },
    { name: "Погрузчик", count: 7 },
    { name: "Паллетоперевозчик электрический самоходный", count: 2 },
    { name: "Гидравлическая тележка (рохля)", count: 6 },
  ]);
  assert.equal(need.equipment.reduce((s, r) => s + r.count, 0), 25, "сходится с «Итого 25»");
  assert.equal(need.months, 24);
});

test("срок: «в течение N месяцев» и даты «с … по …»; нет ни того, ни другого — null", () => {
  assert.equal(termMonths([{ name: "a", text: "Срок оказания услуг: в течение 12 (двенадцати) месяцев с даты заключения" }]), 12);
  assert.equal(termMonths([{ name: "a", text: "Срок оказания услуг – с «01» января 2025 г. по «31» декабря 2026 г." }]), 24);
  assert.equal(termMonths([{ name: "a", text: "Срок выполнения работ: с 15 марта 2026 г. по 14 июня 2026 г." }]), 4, "неполные месяцы считаются целиком");
  assert.equal(termMonths([{ name: "a", text: "Срок поставки — 30 календарных дней" }]), null);
});

test("не состав исполнения: таблица товаров «Наименование | Количество», таблица без должностей, пусто — null; техника без слов о технике рядом не считается", () => {
  assert.equal(findResourceNeed([{ name: "a", text: "Спецификация товаров:\nНаименование | Кол-во единиц\nКабель КГ | 100\nЛента | 20" }]), null, "это товары");
  assert.equal(findResourceNeed([{ name: "a", text: "Участники | Количество\nООО Ромашка | 3" }]), null);
  assert.equal(findResourceNeed([{ name: "a", text: "просто текст без таблиц" }]), null);
  const onlyStaff = findResourceNeed([{ name: "a", text: "Профессия | Численность\nОхранник | 12\nСтарший смены | 3" }]);
  assert.deepEqual(onlyStaff?.staff.map((r) => [r.role, r.count]), [["Охранник", 12], ["Старший смены", 3]]);
  assert.deepEqual(onlyStaff?.equipment, []);
});
