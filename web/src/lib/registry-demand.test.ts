// Распознавание требования о реестровом номере в документах закупки — npm test. Тексты придуманы для проверки, не взяты из закупок.
import assert from "node:assert/strict";
import { test } from "node:test";
import { detectRegistryDemand } from "./registry-demand.ts";

const doc = (name: string, text: string) => ({ name, text });

test("прямое требование номера из реестра российской промышленной продукции — найдено, реестр определён, цитата дословная", () => {
  const text = "Требования к заявке. Участник закупки должен указать в заявке номер реестровой записи из реестра российской промышленной продукции (постановление Правительства Российской Федерации от 17.07.2015 № 719). Остальное — по ТЗ.";
  const d = detectRegistryDemand([doc("Извещение.docx", text)]);
  assert.equal(d.status, "found");
  assert.equal(d.registry, "gisp_rpp_719");
  assert.equal(d.unsupported, null);
  const m = d.mentions.find((x) => x.kind === "rpp_719")!;
  assert.equal(m.role, "requirement");
  assert.equal(m.document, "Извещение.docx");
  assert.ok(text.includes(m.quote), "цитата — точный кусок документа");
});

test("национальный режим без названного реестра — требуется уточнение, а не автоматический выбор реестра", () => {
  const d = detectRegistryDemand([doc("Документация.pdf", "К товарам применяется национальный режим в соответствии с постановлением Правительства Российской Федерации № 1875. Подтверждать происхождение необходимо.")]);
  assert.equal(d.status, "unclear");
  assert.equal(d.registry, null);
  assert.match(d.notes.join(" "), /реестр не назван/);
});

test("реестр российской радиоэлектронной продукции — требование есть, искать нужно в выгрузке радиоэлектронного реестра, а не РПП", () => {
  const d = detectRegistryDemand([doc("ТЗ.docx", "Поставляемое оборудование должно быть включено в реестр российской радиоэлектронной продукции (ПП 878); номер записи указывается в заявке.")]);
  assert.equal(d.status, "found");
  assert.equal(d.registry, "gisp_rep_878");
  assert.equal(d.unsupported, null);
});

test("реестр программ — реестр, которого в системе нет: требование есть, искать негде", () => {
  const d = detectRegistryDemand([doc("ТЗ.docx", "Программное обеспечение должно быть включено в реестр российских программ для электронных вычислительных машин; номер записи указать в заявке.")]);
  assert.equal(d.status, "found");
  assert.equal(d.registry, null);
  assert.equal(d.unsupported, "other_registry");
});

test("назвали два реестра — неясно, какой нужен", () => {
  const d = detectRegistryDemand([
    doc("Извещение", "Товар должен быть в реестре российской промышленной продукции, номер реестровой записи указать в заявке."),
    doc("ТЗ", "Оборудование должно быть в реестре российской радиоэлектронной продукции."),
  ]);
  assert.equal(d.status, "unclear");
  assert.match(d.notes.join(" "), /несколько реестров/);
});

test("оговорка «ограничения не установлены» — требования нет", () => {
  const d = detectRegistryDemand([doc("Извещение", "Ограничения допуска товаров, происходящих из иностранных государств, не установлены. Национальный режим не применяется.")]);
  assert.equal(d.status, "none");
  assert.match(d.notes.join(" "), /не применяются|не применяется/);
});

test("слово «реестр» само по себе ничего не значит: реестр контрактов и недобросовестных поставщиков — не требование", () => {
  const d = detectRegistryDemand([doc("Извещение", "Участник не должен находиться в реестре недобросовестных поставщиков. Сведения о контракте включаются в реестр контрактов.")]);
  assert.equal(d.status, "none");
  assert.equal(d.mentions.length, 0);
});

test("только графа «страна происхождения» — требования о реестровом номере нет, но участнику это сказано", () => {
  const d = detectRegistryDemand([doc("ТЗ", "Таблица: Наименование | Страна происхождения товара | Количество.")]);
  assert.equal(d.status, "none");
  assert.match(d.notes.join(" "), /страну происхождения/);
});

test("реестр программ — другой реестр, которого нет в системе", () => {
  const d = detectRegistryDemand([doc("ТЗ", "Программное обеспечение должно быть включено в единый реестр российских программ для электронных вычислительных машин.")]);
  assert.equal(d.status, "found");
  assert.equal(d.unsupported, "other_registry");
});

test("подсказка: какие позиции названы рядом с требованием", () => {
  const d = detectRegistryDemand(
    [doc("Извещение", "Для кресел офисных необходимо указать номер реестровой записи из реестра российской промышленной продукции. Стол обеденный поставляется без ограничений.")],
    [{ name: "Кресло офисное" }, { name: "Стол обеденный" }, { name: "Шкаф архивный" }],
  );
  assert.equal(d.status, "found");
  assert.deepEqual(d.appliesTo, [0], "стол упомянут в другом предложении, шкаф не упомянут");
});

test("нет документов — требования нет", () => {
  assert.equal(detectRegistryDemand([]).status, "none");
});

// Таблица питательности в меню содержит «0,1875» и «0,719»: это числа, а не постановления № 1875 и № 719.
test("десятичные числа в таблицах не принимаются за номера постановлений", () => {
  const menu = "Молоко 3,2% | | 125 | 125 | 3,625 | 4 | 5,875 | 75 | 1,625 | 150 | 0,125 | 0,05 | 0,1875 | 0,719 | 17,5";
  const d = detectRegistryDemand([doc("Меню.xlsx", menu)]);
  assert.deepEqual(d.mentions, []);
  const real = detectRegistryDemand([doc("Извещение.docx", "Применяется национальный режим в соответствии с постановлением Правительства № 1875, участник указывает страну происхождения.")]);
  assert.ok(real.mentions.some((m) => m.kind === "national_regime"));
});

test("условные абзацы «в случае, если закупаемый товар включён в реестр…» требованием не считаются; настоящее требование находится", () => {
  const conditional = "В случае, если закупаемый товар включен в единый реестр радиоэлектронной продукции, предложение участника должно содержать указание на номер реестровой записи.";
  assert.equal(detectRegistryDemand([doc("Требования.docx", conditional)]).status, "none");
  const real = "Участник должен указать реестровый номер записи в реестре российской промышленной продукции по постановлению Правительства № 719.";
  assert.equal(detectRegistryDemand([doc("Извещение.docx", real)]).status, "found");
});

test("число «1875.93» (плотность в проекте) — не постановление № 1875; ссылка «ПП № 1875.» в конце предложения — по-прежнему постановление", () => {
  const density = detectRegistryDemand([doc("Том 2.pdf", "Средняя плотность - 1875.93, кг/куб.м. Коэффициент пористости 0,48.")]);
  assert.equal(density.status, "none");
  assert.equal(density.mentions.length, 0);
  const real = detectRegistryDemand([doc("Извещение.docx", "Применяется национальный режим по постановлению Правительства № 1875.")]);
  assert.equal(real.mentions[0]?.kind, "national_regime");
});

test("«предоставляется национальный режим» — это не ограничение, а его отсутствие; «не предоставляется» — ограничение действует", () => {
  const granted = detectRegistryDemand([doc("Документация.docx", "21.1. При осуществлении закупки предоставляется национальный режим, обеспечивающий происходящему из иностранного государства товару условия допуска наравне с российским. Участник указывает страну происхождения товара.")]);
  assert.equal(granted.status, "none");
  assert.match(granted.notes.join(" "), /не применяются/);
  const notGranted = detectRegistryDemand([doc("Документация.docx", "1.2.15 Применение законодательства о национальном режиме: Национальный режим не предоставляется. Установлен режим преимущества российской продукции.")]);
  assert.equal(notGranted.status, "unclear");
  assert.match(notGranted.notes.join(" "), /реестр не назван/);
});

test("общие правила «Если в подразделе 1.2 установлен режим запрета…» про все реестры сразу — условия про другой раздел, а не требование к этой закупке", () => {
  const text = [
    "1.2.15 Применение законодательства о национальном режиме: Национальный режим не предоставляется. Установлен режим преимущества российской продукции.",
    "4.13.8 Если в подразделе 1.2 установлен режим запрета закупки иностранной продукции, то заявка с российским программным обеспечением, реестровая запись которого есть в реестре российского программного обеспечения, принимается.",
    "4.13.9 Если в подразделе 1.2 установлен режим ограничения закупки, то заявка с радиоэлектронной продукцией из реестра российской радиоэлектронной продукции (ПП 878) принимается.",
  ].join("\n");
  const d = detectRegistryDemand([doc("Документация.docx", text)]);
  assert.doesNotMatch(d.notes.join(" "), /несколько реестров/);
  assert.equal(d.registry, null);
  assert.equal(d.unsupported, null);
});

test("строки информационной карты «Запрет… | НЕ УСТАНОВЛЕНО» снимают ограничения; «Преимущество… | УСТАНОВЛЕНО» — оставляют (реестр не назван — уточните)", () => {
  const row = (name: string, status: string) => `12.1 | | ${name} товаров (в том числе поставляемых при выполнении закупаемых работ), происходящих из иностранных государств | ${status}`;
  const off = detectRegistryDemand([doc("Карта.docx", [row("Запрет закупок", "НЕ УСТАНОВЛЕНО"), row("Ограничение закупок", "НЕ УСТАНОВЛЕНО"), row("Преимущество в отношении", "НЕ УСТАНОВЛЕНО"), "1.9.1. Предоставление национального режима при осуществлении закупок товаров, работ, услуг."].join("\n"))]);
  assert.equal(off.status, "none");
  assert.match(off.notes.join(" "), /не применяются/);
  const on = detectRegistryDemand([doc("Карта.docx", [row("Запрет закупок", "НЕ УСТАНОВЛЕНО"), row("Преимущество в отношении", "УСТАНОВЛЕНО")].join("\n"))]);
  assert.equal(on.status, "unclear");
  assert.match(on.notes.join(" "), /реестр не назван/);
});
