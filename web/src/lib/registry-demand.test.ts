// Распознавание требования о реестровом номере в документах закупки — npm test. Тексты придуманы для проверки, не взяты из закупок.
import assert from "node:assert/strict";
import { test } from "node:test";
import { detectRegistryDemand } from "./registry-demand.ts";

const doc = (name: string, text: string) => ({ name, text });

test("прямое требование номера из реестра российской промышленной продукции — найдено, реестр определён, цитата дословная", () => {
  const text = "Требования к заявке. Участник закупки должен указать в заявке номер реестровой записи из реестра российской промышленной продукции (постановление Правительства Российской Федерации от 17.07.2015 № 719). Остальное — по ТЗ.";
  const d = detectRegistryDemand([doc("Извещение.docx", text)]);
  assert.equal(d.status, "found");
  assert.equal(d.registry, "gisp_rpp_719");
  assert.equal(d.unsupported, null);
  const m = d.mentions.find((x) => x.kind === "rpp_719")!;
  assert.equal(m.role, "requirement");
  assert.equal(m.document, "Извещение.docx");
  assert.ok(text.includes(m.quote), "цитата — точный кусок документа");
});

test("национальный режим без названного реестра — требуется уточнение, а не автоматический выбор реестра", () => {
  const d = detectRegistryDemand([doc("Документация.pdf", "К товарам применяется национальный режим в соответствии с постановлением Правительства Российской Федерации № 1875. Подтверждать происхождение необходимо.")]);
  assert.equal(d.status, "unclear");
  assert.equal(d.registry, null);
  assert.match(d.notes.join(" "), /реестр не назван/);
});

test("реестр российской радиоэлектронной продукции — требование есть, искать нужно в выгрузке радиоэлектронного реестра, а не РПП", () => {
  const d = detectRegistryDemand([doc("ТЗ.docx", "Поставляемое оборудование должно быть включено в реестр российской радиоэлектронной продукции (ПП 878); номер записи указывается в заявке.")]);
  assert.equal(d.status, "found");
  assert.equal(d.registry, "gisp_rep_878");
  assert.equal(d.unsupported, null);
});

test("реестр программ — реестр, которого в системе нет: требование есть, искать негде", () => {
  const d = detectRegistryDemand([doc("ТЗ.docx", "Программное обеспечение должно быть включено в реестр российских программ для электронных вычислительных машин; номер записи указать в заявке.")]);
  assert.equal(d.status, "found");
  assert.equal(d.registry, null);
  assert.equal(d.unsupported, "other_registry");
});

test("назвали два реестра — неясно, какой нужен", () => {
  const d = detectRegistryDemand([
    doc("Извещение", "Товар должен быть в реестре российской промышленной продукции, номер реестровой записи указать в заявке."),
    doc("ТЗ", "Оборудование должно быть в реестре российской радиоэлектронной продукции."),
  ]);
  assert.equal(d.status, "unclear");
  assert.match(d.notes.join(" "), /несколько реестров/);
});

test("оговорка «ограничения не установлены» — требования нет", () => {
  const d = detectRegistryDemand([doc("Извещение", "Ограничения допуска товаров, происходящих из иностранных государств, не установлены. Национальный режим не применяется.")]);
  assert.equal(d.status, "none");
  assert.match(d.notes.join(" "), /не применяются|не применяется/);
});

test("слово «реестр» само по себе ничего не значит: реестр контрактов и недобросовестных поставщиков — не требование", () => {
  const d = detectRegistryDemand([doc("Извещение", "Участник не должен находиться в реестре недобросовестных поставщиков. Сведения о контракте включаются в реестр контрактов.")]);
  assert.equal(d.status, "none");
  assert.equal(d.mentions.length, 0);
});

test("только графа «страна происхождения» — требования о реестровом номере нет, но участнику это сказано", () => {
  const d = detectRegistryDemand([doc("ТЗ", "Таблица: Наименование | Страна происхождения товара | Количество.")]);
  assert.equal(d.status, "none");
  assert.match(d.notes.join(" "), /страну происхождения/);
});

test("реестр программ — другой реестр, которого нет в системе", () => {
  const d = detectRegistryDemand([doc("ТЗ", "Программное обеспечение должно быть включено в единый реестр российских программ для электронных вычислительных машин.")]);
  assert.equal(d.status, "found");
  assert.equal(d.unsupported, "other_registry");
});

test("подсказка: какие позиции названы рядом с требованием", () => {
  const d = detectRegistryDemand(
    [doc("Извещение", "Для кресел офисных необходимо указать номер реестровой записи из реестра российской промышленной продукции. Стол обеденный поставляется без ограничений.")],
    [{ name: "Кресло офисное" }, { name: "Стол обеденный" }, { name: "Шкаф архивный" }],
  );
  assert.equal(d.status, "found");
  assert.deepEqual(d.appliesTo, [0], "стол упомянут в другом предложении, шкаф не упомянут");
});

test("нет документов — требования нет", () => {
  assert.equal(detectRegistryDemand([]).status, "none");
});
