/** Коэффициент «дорога длиннее прямой»: обычно 1,2–1,4; участник может заменить на свой. */
export const DEFAULT_ROAD_FACTOR = 1.3;

const EARTH_KM = 6371;
const rad = (deg: number) => (deg * Math.PI) / 180;

/** Расстояние по прямой между двумя точками, км (формула гаверсинусов). */
export function straightKm(a: { lat: number; lon: number }, b: { lat: number; lon: number }): number {
  const dLat = rad(b.lat - a.lat);
  const dLon = rad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * EARTH_KM * Math.asin(Math.min(1, Math.sqrt(h)));
}

export type Leg = {
  from: { region: string; center: string };
  to: { region: string; center: string };
  /** Расстояние по прямой между центрами, км (целое). 0 — тот же регион. */
  straight: number;
  factor: number;
  /** Оценка дороги: прямая × коэффициент, км (целое). null — для перевозки не считается. */
  road: number | null;
  /** Почему дорогу не считали. */
  note: string | null;
};

/** Маршрут «ваш регион → место поставки» по названиям регионов из lib/regions.ts. Нет координат или регион один и тот же — null. */
export function legBetween(fromRegion: string, toRegion: string, factor = DEFAULT_ROAD_FACTOR): Leg | null {
  const from = REGION_GEO[fromRegion];
  const to = REGION_GEO[toRegion];
  if (!from || !to || fromRegion === toRegion) return null;
  const straight = Math.round(straightKm(from, to));
  const safe = Number.isFinite(factor) && factor >= 1 && factor <= 3 ? factor : DEFAULT_ROAD_FACTOR;
  const note = from.noRoad ?? to.noRoad ?? null;
  return {
    from: { region: fromRegion, center: from.center },
    to: { region: toRegion, center: to.center },
    straight,
    factor: safe,
    road: note ? null : Math.round(straight * safe),
    note,
  };
}

/** Регион из адреса или места поставки — как в lib/regions.ts. */
export const regionName = (text: string): string | null => regionOf(text)?.name ?? null;
