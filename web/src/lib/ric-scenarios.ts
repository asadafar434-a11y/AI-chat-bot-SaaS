const BY_TYPE: Record<string, ScenarioId> = { goods: "goods", works: "construction", services: "services", it: "it", food: "food", general: "general" };

/** Сфера, которую программа определила по предмету закупки. type — вид закупки из lib/hidden-costs.ts: запасной вариант, когда слов в предмете недостаточно. */
export function scenarioOf(subject: string, type = "general"): ScenarioId {
  for (const [id, re] of RULES) if (re.test(subject)) return id;
  return BY_TYPE[type] ?? "general";
}

// ——— Расчёт поправок и резервов ———

/** Число со знаком: «5», «-3,5», «−12 000». Не число — null. */
export function parseSigned(text: string): number | null {
  const t = String(text ?? "").trim();
  const negative = /^[-−–]/.test(t);
  const n = parseAmount(negative ? t.slice(1) : t);
  return n === null ? null : negative ? -n : n;
}

export type Applied = {
  id: string;
  label: string;
  unit: Unit;
  value: number | null;
  basis: string;
  /** Входит ли в расчёт: нужны число, основание и рассчитанный РИЦ. */
  counted: boolean;
  reason: string | null;
  /** Вклад в рублях (в основе НДС, как у РИЦ); null — не учтена. */
  effect: number | null;
};

export type ScenarioRic = {
  scenario: RicScenario;
  /** Сфера выбрана участником (true) или определена по предмету (false). */
  chosen: boolean;
  base: number | null;
  range: { from: number; to: number } | null;
  adjustments: Applied[];
  /** РИЦ с поправками на условия закупки; null — РИЦ по методу ещё не посчитан полностью. */
  adjusted: number | null;
  adjustedRange: { from: number; to: number } | null;
  risks: Applied[];
  reserve: number | null;
  /** С учётом резерва на отраслевые риски — для расчёта своей цены, не рыночный ориентир. */
  withRisks: number | null;
  /** Начальная цена против РИЦ с поправками: рубли и проценты от РИЦ (плюс — начальная выше). */
  deviation: { abs: number; pct: number } | null;
};

/** Основание поправки — хотя бы пара знаков («КП», «смета», «договор»): пустое число без источника в расчёт не идёт. */
export const MIN_BASIS = 2;
const round2 = (x: number) => Math.round((x + Number.EPSILON) * 100) / 100;

function apply(entry: RicAdjustment | undefined, def: { id: string; label: string; unit: Unit }, base: number | null, ofBase: number | null): Applied {
  const value = entry ? parseSigned(entry.value) : null;
  const basis = (entry?.basis ?? "").trim();
  const filled = entry !== undefined && entry.value.trim() !== "";
  let reason: string | null = null;
  if (filled && value === null) reason = "Не число — впишите цифрами.";
  else if (filled && value === 0) reason = null;
  else if (filled && basis.length < MIN_BASIS) reason = "Нет основания — укажите, откуда число; без него оно в расчёт не идёт.";
  else if (filled && base === null) reason = "РИЦ по методу ещё не посчитан полностью — поправка применится после него.";
  const counted = filled && value !== null && value !== 0 && basis.length >= MIN_BASIS && base !== null && ofBase !== null;
  const effect = counted ? round2(def.unit === "percent" ? (ofBase! * value!) / 100 : value!) : null;
  return { id: def.id, label: def.label, unit: def.unit, value, basis, counted, reason, effect };
}

/** РИЦ по сценарию: РИЦ по методу → поправки на условия закупки (проценты от РИЦ по методу, рубли как есть) → резерв на отраслевые риски (проценты от РИЦ с поправками). Без основания и числа ничего не добавляется. */
export function scenarioRic(data: RicData, result: RicResult, subject: string, type: string): ScenarioRic {
  const chosenScenario = scenarioById(data.scenario);
  const scenario = chosenScenario ?? scenarioById(scenarioOf(subject, type))!;
  const entries = new Map((data.adjustments ?? []).map((a) => [a.id, a]));
  const base = result.ric;

  const adjustments: Applied[] = [
    ...scenario.adjustments.map((def) => apply(entries.get(def.id), def, base, base)),
    ...(data.adjustments ?? []).filter((a) => a.id.startsWith("custom-")).map((a) => apply(a, { id: a.id, label: a.label || "Своя поправка", unit: a.unit ?? "rub" }, base, base)),
  ];
  const adjusted = base === null ? null : round2(base + adjustments.reduce((sum, a) => sum + (a.effect ?? 0), 0));
  const delta = adjusted === null || base === null ? 0 : adjusted - base;
  const shift = (v: number | undefined) => (v === undefined ? null : round2(v + delta));
  const adjustedRange = result.range && adjusted !== null ? { from: shift(result.range.from)!, to: shift(result.range.to)! } : null;

  const risks: Applied[] = scenario.risks.map((def) => apply(entries.get(`risk-${def.id}`), def, adjusted, adjusted));
  const reserve = adjusted === null ? null : round2(risks.reduce((sum, r) => sum + (r.effect ?? 0), 0));
  const withRisks = adjusted === null || reserve === null ? null : round2(adjusted + reserve);
  const nmck = result.nmck;
  const deviation = adjusted !== null && adjusted > 0 && nmck !== null && nmck > 0 ? { abs: round2(nmck - adjusted), pct: ((nmck - adjusted) / adjusted) * 100 } : null;
  return { scenario, chosen: chosenScenario !== null, base, range: result.range, adjustments, adjusted, adjustedRange, risks, reserve, withRisks, deviation };
}

/** Чего не хватает, чтобы РИЦ по сценарию был надёжным: состояние расчёта и данные, которых в программе нет. */
export function readiness(scenario: RicScenario, result: RicResult, data: RicData): { text: string; ok: boolean | null }[] {
  const list: { text: string; ok: boolean | null }[] = [
    { text: result.total > 0 ? `Позиции закупки добавлены: ${result.total}` : "Позиции закупки не добавлены — возьмите их из бланка заказчика или впишите", ok: result.total > 0 },
    { text: "Цена и количество есть по каждой позиции", ok: result.total > 0 ? result.complete : false },
    { text: "По каждой позиции не меньше трёх сопоставимых цен, цены однородны", ok: result.total > 0 ? result.reliable : false },
    { text: result.staleCount > 0 ? `Есть устаревшие цены: ${result.staleCount} — обновите` : "Устаревших цен нет", ok: result.total > 0 ? result.staleCount === 0 : null },
  ];
  for (const b of scenario.basis.filter((x) => x.source === "external")) list.push({ text: `${b.what}: ${b.note}`, ok: null });
  const filled = (data.adjustments ?? []).filter((a) => a.value.trim() !== "" && a.basis.trim().length < MIN_BASIS).length;
  if (filled > 0) list.push({ text: `Поправок или резервов без основания: ${filled} — в расчёт не идут`, ok: false });
  return list;
}

