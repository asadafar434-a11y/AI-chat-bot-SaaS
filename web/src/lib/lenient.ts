import * as z from "zod/v4";

// Поле ответа модели, которое она иногда пропускает или заполняет не из списка. Лишний запрос на исправление стоит денег, а код
// всё равно перепроверяет такие поля по документу, поэтому пропущенное или неверное принимается как «не указано» (fallback).
// В схему для модели поле при этом попадает как обычное обязательное — без «значения по умолчанию», которое подталкивало бы её.
export const lenient = <T extends z.ZodType>(schema: T, fallback: z.output<T>) =>
  z.preprocess((value) => (schema.safeParse(value).success ? value : fallback), schema);
