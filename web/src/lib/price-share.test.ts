// Процент от начальной цены → рубли рядом с условием — npm test.
import assert from "node:assert/strict";
import { test } from "node:test";
import { conditionsOf } from "./conditions.ts";
import { priceShare } from "./price-share.ts";

const QUOTE =
  "наличие опыта исполнения участником закупки договора, предусматривающего оказание услуг общественного питания и (или) поставки пищевых продуктов. Цена оказанных услуг и (или) поставленных товаров по договору должна составлять не менее 20 процентов начальной (максимальной) цены контракта, заключаемого по результатам определения поставщика;";

test("не менее 20 процентов начальной цены 17 млн ₽ — 3 400 000 ₽ (настоящее требование закупки на питание)", () => {
  const [c] = conditionsOf(QUOTE);
  assert.equal(priceShare(c, QUOTE, 17_000_000), "≈ 3 400 000 ₽ от начальной цены");
});

test("копейки не теряются, диапазон считается с двух концов", () => {
  const [c] = conditionsOf("не менее 1,5 процента начальной цены контракта");
  assert.match(priceShare(c, "не менее 1,5 процента начальной цены контракта", 1_000_033.33) ?? "", /≈ 15 000,5 ₽|≈ 15 000,50 ₽/);
  const q = "от 10 до 20 процентов НМЦК";
  const [r] = conditionsOf(q);
  assert.equal(priceShare(r, q, 1_000_000), "≈ от 100 000 ₽ до 200 000 ₽ от начальной цены");
});

test("нет начальной цены или процент не про цену — ничего не показываем", () => {
  const [c] = conditionsOf(QUOTE);
  assert.equal(priceShare(c, QUOTE, null), null);
  const q = "не менее 20 процентов работников должны иметь высшее образование";
  const [p] = conditionsOf(q);
  assert.equal(priceShare(p, q, 17_000_000), null);
  const [n] = conditionsOf("не менее 3 договоров");
  assert.equal(priceShare(n, "не менее 3 договоров", 17_000_000), null);
});
