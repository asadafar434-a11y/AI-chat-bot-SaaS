import * as z from "zod/v4";
import type { PartKey } from "@/lib/my-docs";
import { plural } from "@/lib/plural";
import { PROFILE_GROUPS, type Profile } from "@/lib/profile";

// Анкета, декларация и предложение о цене пишутся по форме заказчика и образцам участника.
// Модель возвращает документ блоками, а файл Word из них собирает сервер — так поля «[…]» остаются жёлтыми.
export const PartDocSchema = z.object({
  title: z.string().describe("Заголовок документа — как в форме заказчика или в образце участника"),
  basis: z
    .string()
    .describe(
      "По чему составлено, коротко, для участника: например «по форме заказчика (приложение № 2 к извещению) и вашему образцу «Анкета.docx»», «по вашему образцу «Анкета.docx»», «по обычной форме — ни формы заказчика, ни образца нет»"
    ),
  blocks: z
    .array(
      z.object({
        type: z
          .enum(["heading", "paragraph", "line", "table"])
          .describe("heading — подзаголовок по центру; paragraph — абзац текста; line — короткая строка без отступа: подпись, дата, М.П., адресат; table — таблица"),
        text: z.string().describe("Текст блока; для table — пустая строка"),
        rows: z.array(z.array(z.string())).describe("Для table — строки таблицы по порядку, ячейки слева направо; для остальных блоков — пустой список"),
      })
    )
    .describe("Документ сверху вниз, без заголовка из title"),
  score: z
    .string()
    .describe(
      "Только для сведений об опыте и о специалистах: сколько баллов, скорее всего, дадут по этому показателю и почему, одной строкой; для остальных документов — пустая строка"
    ),
  gaps: z
    .array(z.string())
    .describe(
      "Только для сведений об опыте и о специалистах: что из документов участника не засчитают и почему, чего не хватает до максимума баллов; для остальных документов — пустой список"
    ),
});

// Оценка баллов и что не засчитают — только для сведений об опыте и о специалистах. У частей, составленных до них,
// этих полей нет: для файла Word они и не нужны.
export type PartDoc = Omit<z.infer<typeof PartDocSchema>, "score" | "gaps"> & { score?: string; gaps?: string[] };
export const PartDocFileSchema = PartDocSchema.omit({ score: true, gaps: true });
export type PartBlock = PartDoc["blocks"][number];

const TASKS: Record<PartKey, string> = {
  participant: "анкету участника закупки — сведения об участнике, которые требует форма заказчика",
  declaration:
    "декларации участника, которые требует форма заказчика, — о принадлежности к субъектам малого и среднего предпринимательства и другие, если они есть в форме, — одним документом, в порядке формы",
  price: "предложение о цене договора",
  experience:
    "сведения об опыте участника по показателю оценки «опыт» — перечень исполненных договоров, которые засчитают по порядку оценки этой закупки",
  staff:
    "сведения о специалистах и иных работниках участника по показателю оценки «специалисты» — тех, кого засчитают по порядку оценки этой закупки",
};

const LABELS = PROFILE_GROUPS.flatMap((g) => g.fields);

export const profileLines = (profile: Profile | null) =>
  LABELS.filter((f) => profile?.[f.key].trim())
    .map((f) => `- ${f.label}: ${profile![f.key].trim()}`)
    .join("\n");

// criteria — выписка из порядка оценки по этому показателю (для сведений об опыте и о специалистах).
type PartTask = { title: string; profile: Profile | null; samples: number; price: string | null; criteria?: string };

// Опыт и специалисты: строки — только из документов участника и только те, что засчитают. Баллы — по шкале
// из порядка оценки; что не засчитают и чего не хватает — в gaps, чтобы участник успел это исправить.
function evidenceRules(part: "experience" | "staff", criteria: string): string {
  const what =
    part === "experience"
      ? `- Строка — один исполненный договор: заказчик, предмет, номер и дата, цена, дата акта о приёмке — в столбцах формы заказчика. Бери их из договора и акта участника.
- Включай только договоры, которые засчитают по порядку оценки: по предмету, сроку исполнения и минимальной цене договора. Договор без акта о приёмке не включай, если порядок оценки требует акт.
- Итоговой строкой — общая цена или количество включённых договоров, смотря что оценивают.`
      : `- Строка — один специалист: фамилия, имя, отчество, должность или роль, образование и квалификация, документ о ней — диплом, удостоверение, допуск с номером и сроком действия, — и основание работы: трудовой или гражданско-правовой договор, — в столбцах формы заказчика.
- Включай только тех, кого засчитают по порядку оценки: нужная роль, образование, группа допуска, действующее удостоверение. Просроченное удостоверение не засчитают.`;
  return `
Сведения:
${what}
- Каждое значение — из документов участника. Чего в них нет, а форма требует, — поле в квадратных скобках. Никого и ничего не придумывай.
- В конце документа — перечень приложений: копии документов, которыми подтверждаются строки, в том же порядке.
- score — сколько баллов, скорее всего, дадут по этому показателю, одной строкой, по шкале или формуле из порядка оценки: например «≈ 100 баллов показателя — 15 из 100 итоговых: общая цена 3 420 000 ₽ выше предельного значения 3 000 000 ₽». Не хватает данных для расчёта — скажи, чего.
- gaps — по строке на каждое «не засчитают» с причиной (договор старше срока, цена ниже минимума, нет акта, удостоверение просрочено, роль не из перечня) и что добавить, чтобы получить больше баллов. Всё засчитают и баллов максимум — пустой список.
${criteria ? `\nКак оценивают по этому показателю — выписка из порядка оценки этой закупки:\n${criteria}\n` : ""}`;
}

// mask — маскировка персональных данных в реквизитах: руководитель, контакты, ИНН и адрес ИП.
export function partInstructions(part: PartKey, { title, profile, samples, price, criteria = "" }: PartTask, mask = (text: string) => text): string {
  const evidence = part === "experience" || part === "staff";
  const priceRules =
    part === "price"
      ? `
Цена и НДС:
- Цена договора: ${price ?? "не указана — оставь поля «[цена цифрами]» и «[цена прописью]»"}. Цифры и сумму прописью переноси ровно так, не пересчитывай.
- НДС пиши так, как в реквизитах в поле «Как писать НДС в цене». Если там пусто — оставь поле «[НДС: ставка и сумма или основание, почему не облагается]». Из образцов НДС не бери: налоговый режим мог измениться.
`
      : "";

  return `Задание: составь ${TASKS[part]} для заявки на эту закупку — отдельным документом, как его готовит опытный тендерный юрист. Если ни форма, ни образец не называют документ иначе, назови его «${title}».

Форма документа, по порядку главенства:
1. Если в документах закупки есть форма этого документа, повтори её состав, порядок, заголовки и постоянный текст дословно. Ничего не добавляй и не пропускай.
2. Всё, чего форма не задаёт, — и весь документ, если формы нет, — делай как в образцах участника: тот же заголовок, те же разделы и таблицы, те же обороты.
3. Если нет ни формы, ни образцов, составь документ в обычном для закупок виде.
${
  evidence
    ? samples
      ? `Перед заданием — документы участника («Документ участника: …»), ${samples} ${plural(samples, "документ", "документа", "документов")}: ${part === "experience" ? "исполненные договоры, акты о приёмке, выписки из реестра контрактов" : "дипломы, удостоверения, допуски, договоры с работниками"}. У длинных документов показаны начало и конец. Это не образцы оформления, а сами сведения.`
      : "Документов участника для этих сведений нет."
    : samples
      ? `Перед заданием — образцы участника того же вида: ${samples} ${plural(samples, "документ", "документа", "документов")}.`
      : "Образцов участника нет."
}

Данные:
- Сведения об участнике — из реквизитов ниже. Если в реквизитах чего-то нет, а в образцах есть постоянные сведения о компании — ОКПО, дата регистрации, сайт, — возьми их из образцов.
- Всё о закупке — номер извещения, предмет, заказчика — только из документов этой закупки. Из образцов не переноси ничего, что относится к другим закупкам: номера, предметы, цены, сроки, даты.
- Чего нет ни в реквизитах, ни в образцах, оставь полем в квадратных скобках с подсказкой, например «[дата]». Ничего не выдумывай.
- Подпись и дату оформи так, как в форме или образце. Подписывает руководитель из реквизитов; расшифровка подписи — из поля «Расшифровка подписи».
${priceRules}${evidence ? evidenceRules(part, criteria) : "\nscore — пустая строка, gaps — пустой список.\n"}
Реквизиты участника:
${mask(profileLines(profile)) || "(не заполнены)"}`;
}
