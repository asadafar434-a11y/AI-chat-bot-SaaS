// Ссылка в ответе ассистента: ИИ пишет разметку, а текст из документов может подсунуть ему что угодно, поэтому ссылкой
// становится только то, что открывается безопасно: адрес на http и https, почта и путь на нашем сайте. «javascript:», «data:»,
// «vbscript:», «file:» — нет. «//чужой-сайт» и «/\чужой-сайт» — тоже: выглядят как путь у нас, а браузер откроет другой сайт.
// Модуль без зависимостей: его проверяют тесты (npm test).
export function isSafeLink(href: string): boolean {
  // Браузер выкидывает из адреса табуляцию и переносы строк и срезает пробелы и управляющие знаки в начале — смотрим на то,
  // что получится после этого, а не на то, как адрес написан.
  const url = href.replace(/[\t\n\r]/g, "").replace(/^[\u0000- ]+/, "");
  return /^(https?:\/\/|mailto:|\/(?![/\\]))/i.test(url);
}
