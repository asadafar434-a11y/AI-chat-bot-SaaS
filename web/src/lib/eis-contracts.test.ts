test("несколько карточек подряд — каждая отдельно; страница без таблицы позиций и мусор — пусто", () => {
  const all = parseEisCards([TUVA, ALTAI, IK1, BARABINSK].join("\n\n"));
  assert.deepEqual(all.map((c) => c.regNumber), ["1170100931726000010", "3224400384226000002", "1040800678526000095", "3545111285226000019"]);
  assert.equal(all.reduce((n, c) => n + c.items.length, 0), 5);
  assert.deepEqual(parseEisCards("№ 1170100931726000010 (Версия № 3 от 22.10.2026)\nЗаказчик\nПРОКУРАТУРА"), []);
  assert.deepEqual(parseEisCards("просто текст"), []);
});

test("цены-аналоги из карточек: цена за единицу как в ЕИС, дата заключения, источник «ЕИС, контракт №», НДС из карточки, пояснение — количество и заказчик", () => {
  const built = eisRows(parseEisCards([TUVA, ALTAI, IK1, BARABINSK].join("\n\n")));
  assert.equal(built.skipped.length, 0);
  assert.deepEqual(built.rows.map((r) => [r.price, r.date, r.source, r.vat]), [
    ["4659,09", "2026-03-31", "ЕИС, контракт № 1170100931726000010", "without"],
    ["3609,6", "2026-05-07", "ЕИС, контракт № 3224400384226000002", "without"],
    ["4314,6", "2026-05-07", "ЕИС, контракт № 3224400384226000002", "without"],
    ["4474,3354", "2026-05-15", "ЕИС, контракт № 1040800678526000095", "with"],
    ["4973,6633", "2026-10-19", "ЕИС, контракт № 3545111285226000019", "with"],
  ]);
  assert.ok(built.rows.every((r) => r.problems.length === 0));
  assert.match(built.rows[0].detail!, /^279,200283746 Т · ПРОКУРАТУРА РЕСПУБЛИКИ ТЫВА · контракт № 9$/);
  assert.match(built.rows[0].name, /^Уголь · Марка Коксовый жирный/);
  const again = eisRows(parseEisCards(`${TUVA}\n${TUVA}`));
  assert.equal(again.rows.length, 1);
  assert.match(again.skipped[0].reason, /повтор/);
});

test("сквозной: пять настоящих цен угля из ЕИС → в РИЦ не идут: это цены контрактов с маржой победителя, нужна закупочная цена", () => {
  const built = eisRows(parseEisCards([TUVA, ALTAI, IK1, BARABINSK].join("\n\n")));
  let n = 0;
  const analogs = toAnalogs(built.rows, "without", () => `e${++n}`);
  const data: RicData = { positions: [{ id: "1", name: "Уголь", unit: "т", qty: "100", analogs }], settings: { ...DEFAULT_SETTINGS, nmckVat: "without" } };
  const result = computeRic(data, 450_000, NOW);
  const p = result.positions[0];
  assert.equal(p.checks.filter((c) => c.state === "used").length, 0);
  assert.ok(p.checks.every((c) => c.state === "invalid" && c.reason === CONTRACT_PRICE_REASON));
  assert.equal(result.ric, null);
});

