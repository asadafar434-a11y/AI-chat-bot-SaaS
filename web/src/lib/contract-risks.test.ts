// Риски и расходы из проекта договора: неустойка (кто платит и сколько), срок оплаты, аванс, обеспечение, расходы исполнителя, изменение объёма — на коротких текстах и на настоящих договорах — npm test (без ИИ).
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { contractRisks, RISK_RULES, type ContractRisk } from "./contract-risks.ts";
import { extractText } from "./extract-text.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../Татьяна-Примеры документов");
const contract = (...lines: string[]) => [{ name: "Проект.docx", text: ["Договор поставки № 1", ...lines].join("\n") }];
const titles = (risks: ContractRisk[], kind?: string) => risks.filter((r) => !kind || r.kind === kind).map((r) => r.title);

async function realRisks(rel: string) {
  const file = path.join(ROOT, rel);
  const r = await extractText(new File([new Uint8Array(readFileSync(file))], path.basename(file)), { ocr: false });
  assert.ok(r.ok, `${rel} не прочитан`);
  return contractRisks([{ name: path.basename(file), text: r.text }]);
}

// Проект договора «Поставка агрегатов сварочных» (АО «ДГК», 23.10.2026), формулировки как в файле: список с тире, сумма цифрами и словами, обеспечение со словами о неустойке.
const DGK = contract(
  "2.10. Обеспечение исполнения обязательств по договору, внесенное Поставщиком в течение 10 (десяти) календарных дней после официальной публикации протокола по выбору победителя в Единой информационной системе в сфере закупок (www.zakupki.gov.ru), в размере 5 (пяти) процентов от цены Договора, (НДС не облагается) на расчетный счет Покупателя, подлежит возврату Поставщику в течение 70 (семьдесят) календарных дней с даты полного исполнения обязательств по заключенному Договору со стороны Поставщика, включая обязательства по оплате неустойки (пеней, штрафов) установленных Договором и возмещения причинённых убытков.",
  "6.1. В случае нарушения Поставщиком обязательств по поставке партии товара (нарушение срока поставки, недопоставка), Покупатель вправе потребовать уплаты Поставщиком:",
  "– неустойки в размере 0,1 (ноль целых и одна десятая) процента от цены несвоевременно поставленной (не поставленной) партии товара за каждый день просрочки – в случае, когда нарушение не привело к изменению срока поставки другому грузополучателю;",
  "–  неустойки в размере 0,2 (ноль целых и две десятых) процента от цены несвоевременно поставленной (не поставленной) партии товара за каждый день просрочки – в случае, когда нарушение привело к изменению срока поставки другому грузополучателю.",
  "6.5. В случае нарушения Поставщиком сроков, предусмотренных пунктом 4.1.4. настоящего Договора, Покупатель также имеет право требовать от Поставщика уплаты штрафа в размере 50 000 (пятидесяти тысяч) рублей за каждый случай нарушения.",
  "6.6. В случае поступления Товара несоответствующего сведениям о стране происхождения Товара, согласованного в договоре, Покупатель вправе взыскать с Поставщика штраф в размере 10% от стоимости поставленного Товара.",
);

test("договор ДГК: обеспечение исполнения 5 % — это обеспечение, а не «пеня 5 %»; слова «неустойки (пеней, штрафов)» в нём — условие возврата денег", () => {
  const risks = contractRisks(DGK);
  assert.deepEqual(titles(risks, "security"), ["Обеспечение исполнения: 5 %"]);
  assert.ok(!titles(risks, "penalty").some((t) => /^Пеня 5 %/.test(t)), "пени 5 % в договоре нет");
  assert.equal(risks.find((r) => r.kind === "security")?.clause, "2.10");
});

test("договор ДГК: пункты списка «– неустойки в размере 0,1 % … 0,2 % за каждый день» берут «кто платит» из вводной строки; сумма цифрами и словами и «за каждый случай» читаются; за что штраф — из слов договора", () => {
  const mine = contractRisks(DGK).filter((r) => r.kind === "penalty" && r.party === "you");
  assert.deepEqual(titles(mine), [
    "Пеня 0,1 %, за каждый день просрочки, от цены несвоевременно поставленной",
    "Пеня 0,2 %, за каждый день просрочки, от цены несвоевременно поставленной",
    "Штраф 50 000 ₽, за каждый случай нарушения",
    "Штраф 10 %, от стоимости поставленного Товара",
  ]);
  assert.deepEqual(mine.map((r) => r.clause).slice(0, 2), ["6.1", "6.1"], "пункт списка — пункт его вводной строки");
  assert.equal(mine[2].n?.rub, 50000, "сумма цифрами, слова в скобках не мешают");
  assert.equal(mine[2].cause, "нарушение сроков");
  assert.equal(mine[3].cause, "несоответствие страны происхождения");
  assert.equal(mine[0].cause, undefined, "причина — только по прямым словам договора");
});

test("неустойка: кто платит и сколько — вы или заказчик; пеня за день и штраф разведены, крупные помечены, потолок виден", () => {
  const risks = contractRisks(
    contract(
      "7.3. В случае просрочки исполнения Исполнителем своих обязательств Исполнитель обязан уплатить Заказчику пеню в размере 0,1% от цены Договора за каждый день просрочки.",
      "7.4. За нарушение Исполнитель уплачивает Заказчику штраф в размере 30% от цены Договора.",
      "6.2. В случае нарушения Заказчиком сроков оплаты Заказчик выплачивает Исполнителю пеню в размере 0,01% от суммы долга за каждый день просрочки, но не более 10 (десяти) % цены Договора.",
      "6.5. Заказчик вправе потребовать уплаты неустойки в случае нарушения сроков, предусмотренных Договором, без указания размера.",
    ),
  );
  const mine = risks.filter((r) => r.party === "you");
  assert.deepEqual(titles(mine), ["Пеня 0,1 %, за каждый день просрочки, от цены Договора", "Штраф 30 %, от цены Договора"]);
  assert.equal(mine[0].heavy, undefined, "0,1 % в день — не крупная");
  assert.equal(mine[1].heavy, true, "штраф от 20 % — крупный");
  assert.equal(mine[0].level, "warn");
  const theirs = risks.filter((r) => r.party === "customer");
  assert.deepEqual(titles(theirs), ["Пеня 0,01 %, за каждый день просрочки, от суммы долга, не более 10 % цены"]);
  assert.equal(theirs[0].level, "info");
  assert.equal(risks.length, 3, "неустойка без размера в риски не попадает");
  assert.equal(mine[0].clause, "7.3");
});

