test("каждая находка с цитатой, пунктом и файлом; цитата не длиннее 260 знаков; те же слова не из договора (извещение) в риски не идут", () => {
  const long = `7.3. Исполнитель обязан уплатить Заказчику пеню в размере 0,1% от цены Договора за каждый день просрочки ${"и далее по тексту ".repeat(30)}.`;
  const [r] = contractRisks(contract(long));
  assert.ok(r.quote.length <= 260);
  assert.equal(r.clause, "7.3");
  assert.equal(r.doc, "Проект.docx");
  const notice = [{ name: "Извещение.pdf", text: "Извещение о закупке\nИсполнитель обязан уплатить Заказчику пеню в размере 0,1% от цены за каждый день просрочки обязательств." }];
  assert.deepEqual(contractRisks(notice), [], "извещение — не проект договора");
});

