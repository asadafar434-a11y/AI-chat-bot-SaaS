test("настоящие договоры «Россети Сибирь», охраны, Метростроя, Семикаракорска и угля: обеспечение 10 % и расходы на гарантию, потолок пени заказчика, обеспечение не установлено, аванса нет и 1 %, одна пеня заказчика", async () => {
  const rosseti = await realRisks("Россети Сибирь (закупка в электронном магазине, мебель)/2026.08.21 1001759664 договор.docx");
  assert.ok(rosseti.some((r) => r.title === "Обеспечение исполнения: 10 %" && r.level === "warn"));
  assert.ok(rosseti.some((r) => r.title === "Расходы за ваш счёт: обеспечение (банковская гарантия)"));
  assert.equal(rosseti.filter((r) => r.kind === "advance").length, 0, "оговорки «в случае, если проект…» — не аванс");
  const guard = await realRisks("КРМО (конкурс МСП 223-ФЗ, охрана индустриального парка Есипово)/Проект Договора Охрана.docx");
  assert.ok(guard.some((r) => r.party === "customer" && /не более 10 % цены/.test(r.title)));
  assert.ok(guard.some((r) => r.kind === "payment" && /7 рабочих дней с даты подписания Сторонами Акта/.test(r.title)));
  const metro = await realRisks("Метрострой СС (аукцион МСП 223-ФЗ, сетка стальная)/Проект договора.docx");
  assert.deepEqual(titles(metro, "security"), ["Обеспечение исполнения не установлено"]);
  const kids = await realRisks("Детские сады Семикаракорска (аукцион, питание)/Приложение № 4 Проект контракта.docx");
  assert.ok(kids.some((r) => /Аванса нет/.test(r.title)));
  assert.ok(kids.some((r) => r.title === "Обеспечение исполнения: 1 %"));
  const coal = await realRisks("МУП Тепло Корсаков (аукцион 223-ФЗ, уголь)/Договор поставки угля.docx");
  assert.deepEqual(titles(coal, "penalty"), ["Пеня 1/300 ключевой ставки, за каждый день просрочки, от суммы платежа"]);
  assert.equal(coal[0].party, "customer");
  assert.deepEqual(titles(coal, "price"), ["Договор допускает изменение цены: при изменении ставки НДС", "Договор допускает изменение цены: индексация по индексам потребительских цен, не реже раза в 6 мес."]);
});

